def check_settings(settings, level, mode=None):
    """Stop, listing every setting of `settings` ({name: value}; a dict value is searched one level down, its keys
    reported as NAME['key']) that still holds SET_ME, with where it lives and what to set. A setting of the other
    segmentation than `mode` is not required; with mode None or unset every setting is listed."""
    unset = []
    for name, value in settings.items():
        items = [(f"{name}[{k!r}]", v) for k, v in value.items()] if isinstance(value, dict) else [(name, value)]
        unset += [key for key, v in items if isinstance(v, str) and v == SET_ME]
    if mode in ("dynamic", "predefined"):
        unset = [k for k in unset if SET_ME_GUIDE.get(k, ("", "", "both"))[2] in ("both", mode)]
    if not unset:
        print(f'settings check ({level}): no setting holds "SET_ME"')
        return
    lines = []
    for key in unset:
        where, what, m = SET_ME_GUIDE.get(key, ("see the comment beside it", "", "both"))
        lines.append(f"  - {key}  ({where}{'' if m == 'both' else '; ' + m + ' segmentation only'})"
                     + (f"\n      {what}" if what else ""))
    raise SystemExit(f'settings check ({level}): {len(unset)} setting(s) still hold "SET_ME". Set each, then run '
                     'again (README, "Settings"; a script is built from its notebook: set the value there and rerun '
                     "build_level_scripts.py):\n" + "\n".join(lines))


