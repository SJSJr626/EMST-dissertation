def _predict_from_params(trials: np.ndarray, p) -> np.ndarray:
    """
    Reconstruct predictions from a params row, dispatching to the correct model.
    
    Parameters
    ----------
    trials : array-like
        Trial indices to predict for.
    p : dict-like (Series or dict)
        Must contain 'model_name' key and all parameter values for that model.
    
    Returns
    -------
    predicted : np.ndarray
        Predicted RT values.
    """
    mname = p.get('model_name', 'exp_w_linfag')  # default when the row has no model_name
    # an unknown or corrupted model_name string is replaced by exp_w_linfag, with a warning
    if mname not in DRIFT_MODELS:
        import warnings as _w_h1
        _w_h1.warn(
            f"_predict_from_params: unknown model_name='{mname}'; using 'exp_w_linfag'",
            stacklevel=2,
        )
        mname = 'exp_w_linfag'
    spec = DRIFT_MODELS[mname]
    model_fn = spec["function"]
    param_names = spec["param_names"]
    pvals = [p[pn] for pn in param_names]
    return model_fn(np.asarray(trials, dtype=float), *pvals)

