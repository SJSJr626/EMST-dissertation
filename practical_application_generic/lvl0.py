    if len(rt_vals) > 10:
        _, lam = stats.boxcox(rt_vals)
    else:
        lam = 0.0  # too few RTs: lambda 0 (the log transform)
    scale_lambdas[scale_name] = lam
    idx = grp.index[mask]
    if abs(lam) < 1e-10:
        clean_data.loc[idx, 'bc_rt'] = np.log(clean_data.loc[idx, 'rt_sec'])
    else:
        clean_data.loc[idx, 'bc_rt'] = (clean_data.loc[idx, 'rt_sec'] ** lam - 1) / lam
    clean_data.loc[grp.index, 'bc_lambda'] = lam
