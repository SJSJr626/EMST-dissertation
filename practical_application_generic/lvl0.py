# PERIODIC RESPONSE PATTERNS
# Extends the straight-line machinery from period 1 (the same key repeated) to the periods
# 2 ... S-1 for S scales per stimulus (periodic_periods; e.g. 1-2-1-2-1, 1-2-3-1-2-3).
# DESIGN NOTES:
#   * Runs are computed on the `resp_order` axis -- the interleaved keypress stream --
#     NOT within scale. A disengaged rater oscillating 1-2-1-2 does so in KEY space; the
#     values land on whichever of the S scales happens to be current. Computing these
#     within scale would look for the pattern in the one place it is not.
#   * The permutation null shuffles each participant-session's responses FREELY, across
#     scales, exactly as permutation_null_straight_line already does. Constraining the
#     shuffle within scale would preserve the very structure the null is meant to
#     destroy, making the test anti-conservative.
#   * Period S is not included here: a period-S repeat across resp_order is the same
#     S-tuple repeated across stimuli (the scales are answered in a fixed order), which is
#     exactly what detect_inattentive_patterns already detects on the stim_order axis.
#     Adding it here would double-count.
#   * A RUN COUNTS FOR PERIOD p ONLY IF ITS MINIMAL PERIOD IS p.
#     A run is attributed to period p only where the same span is NOT wholly explained
#     by a proper divisor of p (_proper_divisors: 1 for p=2 and p=3; 1 and 2 for p=4). A
#     plain lag rule ("value[i] == value[i-p] repeatedly") would count every constant run
#     as a run of every period, of the same length (a constant series satisfies every lag), and a
#     1-2-1-2 run also at p=4 (lag-2 equality implies lag-4 equality), in the
#     diagnostics and the permutation null alike. The minimal-period rule makes the periodic
#     detectors mutually exclusive and disjoint from straight-lining BY CONSTRUCTION, in
#     the observed data and in the null alike -- no masking order, no threshold
#     circularity. mask_shorter in detect_periodic_patterns is a second guard, not the
#     mechanism.
# ======================================================================================

def periodic_periods(n_scales):
    """The periods of the periodic-pattern markers for n_scales scales per stimulus: 2 ... n_scales - 1 (period 1 is
    straight-lining, period n_scales the stimulus-linked pattern)."""
    return tuple(range(2, int(n_scales)))


def _proper_divisors(p):
    """Proper divisors of period p: the shorter explanations a period-p run must survive."""
    return tuple(d for d in range(1, p) if p % d == 0)


# No threshold is set in this cell: its diagnostics show the null percentiles, and the
# values applied are LVL_2_CONFIG's inattent_behav_periodic_thresh, {period: run length}
# (add_trial_markers).


def _periodic_response_array(responses) -> np.ndarray:
    """Responses as float64 with non-numeric/masked entries as NaN.

    NaN != NaN, so gaps break runs automatically in the vectorised comparisons below.
    """
    return pd.to_numeric(pd.Series(responses), errors="coerce").to_numpy(dtype=float)


def _lag_match_mask(arr: np.ndarray, lag: int) -> np.ndarray:
    """mask[i] is True where arr[i] == arr[i - lag] (False for i < lag and for NaN)."""
    mask = np.zeros(arr.size, dtype=bool)
    if arr.size > lag:
        np.equal(arr[lag:], arr[:-lag], out=mask[lag:])
    return mask


def _true_run_bounds(mask: np.ndarray):
    """(starts, stops) of the maximal True runs in `mask`; mask[start:stop] is all True."""
    edges = np.flatnonzero(np.diff(np.concatenate(([0], mask.view(np.int8), [0]))))
    return edges[0::2], edges[1::2]


def _periodic_max_runs(arr: np.ndarray, periods) -> dict:
    """Longest MINIMAL-period run length, in trials, for each requested period.

    One pass, shared lag masks -- this is the hot path for the permutation null.
    Length is counted in TRIALS, so 1-2-1-2-1 has a period-2 run of 5.
    """
    lags = sorted(set(periods) | {d for p in periods for d in _proper_divisors(p)})
    masks = {lag: _lag_match_mask(arr, lag) for lag in lags}

    out = {}
    for period in periods:
        m = masks[period]
        best = 0
        if m.any():
            div_masks = [masks[d] for d in _proper_divisors(period)]
            for start, stop in zip(*_true_run_bounds(m)):
                # Wholly explained by a shorter period? Then it is that pattern, not this one.
                if any(dm[start:stop].all() for dm in div_masks):
                    continue
                best = max(best, stop - (start - period))
        out[period] = int(best)
    return out



def _periodic_run_lengths(responses, period: int) -> np.ndarray:
    """Per-trial run length for a given period; 0 where the trial is not in such a run."""
    arr = _periodic_response_array(responses)
    out = np.zeros(arr.size, dtype=int)
    if arr.size <= period:
        return out

    m = _lag_match_mask(arr, period)
    if not m.any():
        return out

    div_masks = [_lag_match_mask(arr, d) for d in _proper_divisors(period)]
    for start, stop in zip(*_true_run_bounds(m)):
        if any(dm[start:stop].all() for dm in div_masks):
            continue
        a, b = start - period, stop
        # Consecutive runs can share their first `period` trials; keep the longer claim.
        np.maximum(out[a:b], b - a, out=out[a:b])
    return out


def _perm_null_periodic_session(responses, seed, n_permutations, periods):
    """One participant-session's whole null: (n_permutations, len(periods)) of max runs.

    Parallelised over SESSIONS rather than over individual permutations: one joblib task
    per permutation (572,000 tasks of ~1 ms) would spend most of its wall time in dispatch.
    """
    rng = np.random.default_rng(seed)
    arr = _periodic_response_array(responses)
    out = np.empty((n_permutations, len(periods)), dtype=int)
    for i in range(n_permutations):
        rng.shuffle(arr)
        maxima = _periodic_max_runs(arr, periods)
        out[i] = [maxima[p] for p in periods]
    return out


def permutation_null_periodic_all(
    df: pd.DataFrame,
    periods,
    n_permutations: int = 1000,
    response_col: str = "response",
    id_col: str = "id",
    session_col: str = "session",
    stim_col: str = "resp_order",
    random_state: int = 42,
    _n_jobs: int = None,
) -> dict:
    """Null distributions of max minimal-period run length PER participant-session.

    Returns {period: {(pid, session): np.ndarray}}, i.e. one plot_threshold_analysis-ready
    dict per period. All periods are read off the SAME shuffles, so the panels differ only
    because the patterns differ, not because the draws did.
    """
    periods = tuple(periods)
    if _n_jobs is None:
        try:
            _n_jobs = n_jobs
        except NameError:
            _n_jobs = -1

    rng = np.random.default_rng(random_state)
    keys, responses = [], []
    for (pid, sess), group in df.groupby([id_col, session_col], sort=False):
        keys.append((pid, sess))
        responses.append(group.sort_values(stim_col)[response_col].to_numpy())

    seeds = rng.integers(0, 2**31, size=len(keys))
    results = Parallel(n_jobs=_n_jobs)(
        delayed(_perm_null_periodic_session)(r, s, n_permutations, periods)
        for r, s in zip(responses, seeds)
    )

    null = {p: {} for p in periods}
    for key, res in zip(keys, results):
        for j, p in enumerate(periods):
            null[p][key] = res[:, j]
    return null



def compute_observed_max_runs_periodic_all(
    df: pd.DataFrame,
    periods,
    response_col: str = "response",
    id_col: str = "id",
    session_col: str = "session",
    stim_col: str = "resp_order",
) -> dict:
    """Observed max minimal-period run per participant-session -> {period: {key: value}}."""
    periods = tuple(periods)
    observed = {p: {} for p in periods}
    for (pid, sess), group in df.groupby([id_col, session_col], sort=False):
        arr = _periodic_response_array(group.sort_values(stim_col)[response_col].to_numpy())
        maxima = _periodic_max_runs(arr, periods)
        for p in periods:
            observed[p][(pid, sess)] = maxima[p]
    return observed



def detect_periodic_patterns(
    df: pd.DataFrame,
    periodic_thresh: dict,
    response_col: str = "response",
    id_col: str = "id",
    session_col: str = "session",
    stim_col: str = "resp_order",
    mask_shorter: bool = True,
) -> pd.DataFrame:
    """Flag trials in periodic runs at or above the configured thresholds.

    Adds, for each period p of periodic_thresh (in increasing order): `is_periodic_p{p}` and
    `p{p}_run_length`; plus a convenience union column `is_any_periodic`.

    Thresholds come from `periodic_thresh`, {period: minimum run length in trials}; a
    threshold of 0 disables that period.

    Attribution to the shortest period that explains a run is structural (see the
    minimal-period note at the top of this block). mask_shorter is a second
    guard: it drops straight-lined trials, and trials already claimed by a shorter
    period, out of the series before the next period is scanned.
    """
    df = df.copy()
    work = df[response_col].copy()

    if mask_shorter and "is_straight_line" in df.columns:
        work = work.mask(df["is_straight_line"].fillna(False))

    for period in sorted(periodic_thresh):
        thresh = int(periodic_thresh[period])
        flag_col, len_col = f"is_periodic_p{period}", f"p{period}_run_length"
        df[flag_col], df[len_col] = False, 0
        if thresh <= 0:
            continue
        for _, group in df.groupby([id_col, session_col], sort=False):
            idx = group.sort_values(stim_col).index.to_numpy()
            runs = _periodic_run_lengths(work.loc[idx].to_numpy(), period)
            df.loc[idx, len_col] = runs
            df.loc[idx, flag_col] = runs >= thresh
        if mask_shorter:
            work = work.mask(df[flag_col])

    periodic_cols = [f"is_periodic_p{p}" for p in sorted(periodic_thresh)]
    df["is_any_periodic"] = df[periodic_cols].any(axis=1)
    return df


def add_trial_markers(
    df: pd.DataFrame,
    sl_thresh: int,
    periodic_thresh: dict,
    ip_thresh: int,
    fast_rt_thresh: float,
    fast_rt_scales=None,
    rt_col: str = "rt_sec",
    scale_col: str = "scale",
) -> pd.DataFrame:
    """The trial-level careless-responding markers: the one implementation of them.

    Adds, in this order:
      is_straight_line, sl_run_length      straight-lining (detect_straight_lines)
      is_periodic_p{p}, p{p}_run_length, is_any_periodic
                                           periodic patterns, one per period p of periodic_thresh
                                           ({period: run length}), straight-lined trials masked
                                           (detect_periodic_patterns)
      is_inattentive_pattern, ip_run_length
                                           stimulus-linked pattern, straight-lined
                                           trials masked (detect_inattentive_patterns)
      is_fast_rt                           rt_col below fast_rt_thresh, on fast_rt_scales
                                           (None = every scale)

    Runs are counted within each participant-session on the sequence passed in; pass the
    unfiltered sequence, the one the permutation nulls of this cell are built on. Every
    threshold is an argument and nothing is read from a config; 0 disables a marker.
    LVL_2 calls this at load ([cell 29]) with its inattent_behav_* settings; LVL_0 calls it
    only for its display copy.
    """
    df = detect_straight_lines(df, sl_thresh)
    df = detect_periodic_patterns(df, periodic_thresh)
    df = detect_inattentive_patterns(df, stim_ip_thresh=ip_thresh, mask_straight_lines=True)
    _on = df[scale_col].isin(fast_rt_scales) if fast_rt_scales is not None else True
    df["is_fast_rt"] = (df[rt_col] < fast_rt_thresh) & _on
    return df


