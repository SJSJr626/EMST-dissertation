def plot_rt_threshold_analysis(
    df: pd.DataFrame,
    rt_col: str = "rt_sec",
    id_col: str = "id",
    percentiles_slow: list = [95, 99],
    percentiles_fast: list = [1, 5],
    current_max_thresh: float = None,
    current_min_thresh: float = None,
) -> tuple[plt.Figure, dict]:
    """
    Data-driven RT threshold analysis using empirical percentiles.
    
    Parameters
    ----------
    df : pd.DataFrame
        Long-format data with RT column
    rt_col : str
        Column containing RT values
    percentiles_slow : list
        Percentiles to suggest for slow RT threshold (upper tail)
    percentiles_fast : list
        Percentiles to suggest for fast RT threshold (lower tail)
    current_max_thresh, current_min_thresh : float
        Current threshold settings to display
    
    Returns
    -------
    tuple: (plt.Figure, dict of suggested thresholds)
    """
    rts = df[rt_col].dropna().values
    
    fig, axes = plt.subplots(1, 2, figsize=(14, 5))
    
    suggested_thresholds = {"slow": {}, "fast": {}}
    colors = plt.cm.Reds(np.linspace(0.4, 0.9, max(len(percentiles_slow), len(percentiles_fast))))

    
    # === LEFT: Slow RT analysis ===
    ax = axes[0]
    
    # Histogram of all RTs (focus on upper tail)
    rt_99 = np.percentile(rts, 99.5)
    bins = np.linspace(0, min(rt_99 * 1.2, rts.max()), 100)
    ax.hist(rts, bins=bins, density=True, alpha=0.7, color="steelblue", 
            edgecolor="black", label="RT distribution")
    
    # Mark percentile thresholds for slow RTs
    for i, pct in enumerate(percentiles_slow):
        thresh = np.percentile(rts, pct)
        suggested_thresholds["slow"][pct] = thresh
        ax.axvline(thresh, color=colors[i % len(colors)], linestyle="--", linewidth=2,
                   label=f"{pct}th percentile: {thresh:.2f}s")
    
    if current_max_thresh is not None:
        ax.axvline(current_max_thresh, color="green", linestyle="-", linewidth=2,
                   label=f"Current threshold: {current_max_thresh}s")
    
    ax.set_xlabel("Response Time (seconds)")
    ax.set_ylabel("Density")
    ax.set_title(f"Slow RT Threshold Analysis (n={len(rts):,} trials)")
    ax.legend(loc="upper right")
    ax.set_xlim(0, min(rt_99 * 1.2, rts.max()))
    
    # === RIGHT: Fast RT analysis ===
    ax = axes[1]
    
    # Histogram focused on lower tail
    rt_10 = np.percentile(rts, 10)
    bins = np.linspace(0, rt_10 * 3, 100)
    ax.hist(rts[rts < rt_10 * 3], bins=bins, density=True, alpha=0.7, color="steelblue", 
            edgecolor="black", label="RT distribution (lower tail)")
    
    # Mark percentile thresholds for fast RTs
    for i, pct in enumerate(percentiles_fast):
        thresh = np.percentile(rts, pct)
        suggested_thresholds["fast"][pct] = thresh
        ax.axvline(thresh, color=colors[i % len(colors)], linestyle="--", linewidth=2,
                   label=f"{pct}th percentile: {thresh:.3f}s")
    
    if current_min_thresh is not None:
        ax.axvline(current_min_thresh, color="green", linestyle="-", linewidth=2,
                   label=f"Current threshold: {current_min_thresh}s")
    
    ax.set_xlabel("Response Time (seconds)")
    ax.set_ylabel("Density")
    ax.set_title(f"Fast RT Threshold Analysis (n={len(rts):,} trials)")
    ax.legend(loc="upper right")
    
    plt.tight_layout()
    
    # Print summary
    n_total = len(rts)
    print("=" * 70)
    print("RT THRESHOLD ANALYSIS (Empirical Percentiles)")
    print("=" * 70)
    print(f"Total trials: {n_total:,}")
    print(f"RT range: {rts.min():.3f}s - {rts.max():.1f}s")
    print(f"Median RT: {np.median(rts):.2f}s")
    print(f"Mean RT: {np.mean(rts):.2f}s")
    print("-" * 70)
    
    print("SLOW RT thresholds (upper tail):")
    for pct in percentiles_slow:
        thresh = suggested_thresholds["slow"][pct]
        n_exceed = np.sum(rts > thresh)
        pct_exceed = 100 * n_exceed / n_total
        print(f"  {pct}th percentile: {thresh:.2f}s ({n_exceed:,} trials exceed, {pct_exceed:.1f}%)")
    if current_max_thresh is not None:
        n_exceed = np.sum(rts > current_max_thresh)
        pct_exceed = 100 * n_exceed / n_total
        print(f"  Current threshold ({current_max_thresh}s): {n_exceed:,} trials exceed ({pct_exceed:.2f}%)")
    
    print("-" * 70)
    print("FAST RT thresholds (lower tail):")
    for pct in percentiles_fast:
        thresh = suggested_thresholds["fast"][pct]
        n_below = np.sum(rts < thresh)
        pct_below = 100 * n_below / n_total
        print(f"  {pct}th percentile: {thresh:.3f}s ({n_below:,} trials below, {pct_below:.1f}%)")
    if current_min_thresh is not None:
        n_below = np.sum(rts < current_min_thresh)
        pct_below = 100 * n_below / n_total
        print(f"  Current threshold ({current_min_thresh}s): {n_below:,} trials below ({pct_below:.2f}%)")
    
    # Per-participant summary
    print("-" * 70)
    print("Per-participant analysis:")
    participant_medians = df.groupby(id_col)[rt_col].median()
    print(f"  Median RT range across participants: {participant_medians.min():.2f}s - {participant_medians.max():.2f}s")
    print(f"  Mean of participant medians: {participant_medians.mean():.2f}s")
    print("=" * 70)
    
    return fig, suggested_thresholds


def plot_slow_rt_by_participant(
    df: pd.DataFrame,
    config: dict,  
    rt_col: str = "rt_sec",
    id_col: str = "id",
) -> plt.Figure:
    """
    Show participants with the slowest RTs.
    """
    # 1. Extract parameters from the config dictionary first
    slow_threshold = config["max_rt_thresh"]
    top_n = config["sub_n_plots"]

    # 2. Perform the data aggregation
    stats_df = df.groupby(id_col).agg(
        n_trials=(rt_col, "count"),
        n_slow=(rt_col, lambda x: (x > slow_threshold).sum()), # Count slow responses (based on max_rt_thresh)
        max_rt=(rt_col, "max"),
        median_rt=(rt_col, "median"),
    ).reset_index()

    # zero-guard so participants with all-NaN RT do not yield inf/NaN.
    stats_df["pct_slow"] = np.where(
        stats_df["n_trials"] > 0,
        100 * stats_df["n_slow"] / stats_df["n_trials"].replace(0, np.nan),
        0.0,
    )
    stats_df = stats_df[stats_df["n_trials"] > 0]
    stats_df = stats_df.sort_values("pct_slow", ascending=False).head(top_n)

    fig, axes = plt.subplots(1, 2, figsize=(12, 5))

    ax = axes[0]
    ax.barh(range(len(stats_df)), stats_df["pct_slow"])
    ax.set_yticks(range(len(stats_df)))
    ax.set_yticklabels(stats_df[id_col].astype(str))
    ax.set_xlabel(f"% Data (Trials) > {slow_threshold:.1f}s")
    ax.set_ylabel("Participant ID")
    ax.set_title(f"Top {top_n} Participants by Slow RT Rate")
    ax.axvline(10, linestyle="--", alpha=0.7, label="10% threshold")
    ax.legend()
    ax.invert_yaxis()

    ax = axes[1]
    all_stats = df.groupby(id_col).agg(
        n_trials=(rt_col, "count"),
        n_slow=(rt_col, lambda x: (x > slow_threshold).sum()),
        median_rt=(rt_col, "median"),
    ).reset_index()
    # zero-guard
    all_stats["pct_slow"] = np.where(
        all_stats["n_trials"] > 0,
        100 * all_stats["n_slow"] / all_stats["n_trials"].replace(0, np.nan),
        0.0,
    )

    ax.scatter(all_stats["median_rt"], all_stats["pct_slow"], alpha=0.5, s=30)
    ax.axhline(10, linestyle="--", alpha=0.7, label="10% threshold")
    ax.set_xlabel("Median RT (seconds)")
    ax.set_ylabel(f"% Data (Trials) > {slow_threshold:.1f}s")
    ax.set_title("Slow RT Rate vs Median RT")
    ax.legend()

    fig.tight_layout()
    return fig


