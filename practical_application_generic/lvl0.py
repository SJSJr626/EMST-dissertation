def detect_inattentive_patterns(
    df: pd.DataFrame,
    stim_ip_thresh: int,
    response_col: str = "response",
    id_col: str = "id",
    session_col: str = "session",
    scale_col: str = "scale",
    stim_col: str = "stim_order",
    mask_straight_lines: bool = True,
    _n_jobs: int = None
) -> pd.DataFrame:
    """
    Detect inattentive response patterns: identical response vectors across consecutive stimuli.
    
    This detects when a participant gives the SAME response pattern to consecutive stimuli,
    i.e., their response vector (across all scales) for stimulus N is identical to stimulus N-1.
    
    For example, if a participant rates:
        Stimulus 1: scale_1=1, scale_2=2, …
        Stimulus 2: scale_1=1, scale_2=2, …
        Stimulus 3: scale_1=1, scale_2=2, …
    
    This is a stimulus-linked pattern - they're not differentiating between stimuli.
    
    Parameters
    ----------
    df : pd.DataFrame
        Long-format data with responses
    stim_ip_thresh : int
        Minimum consecutive identical stimulus response vectors to flag as inattentive
    response_col : str
        Column containing response values
    id_col : str
        Column containing participant IDs
    session_col : str
        Column containing session numbers
    scale_col : str
        Column containing scale names
    stim_col : str
        Column containing stimulus order
    mask_straight_lines : bool
        If True, exclude already-flagged straight-line responses before detection
        (requires 'is_straight_line' column)
    n_jobs : int
        Number of parallel workers
    
    Returns
    -------
    pd.DataFrame
        DataFrame with added columns:
        - is_inattentive_pattern: bool, whether trial is part of a stimulus-linked pattern
        - ip_run_length: int, length of the stimulus-linked pattern run (in stimuli)
    """
    df = df.copy()
    
    if stim_ip_thresh <= 0:
        df["is_inattentive_pattern"] = False
        df["ip_run_length"] = 0
        return df
    
    # Resolve n_jobs (use global n_jobs if not specified)
    if _n_jobs is None:
        try:
            _n_jobs = n_jobs  # global n_jobs set in the BLAS/thread-limits cell
        except NameError:
            _n_jobs = 1
    _n_jobs = max(1, int(_n_jobs))
    
    # Remove existing columns if present
    for col in ["is_inattentive_pattern", "ip_run_length"]:
        if col in df.columns:
            df = df.drop(columns=[col])
    
    # Initialize columns
    df["is_inattentive_pattern"] = False
    df["ip_run_length"] = 0
    
    # Create working copy, masking straight-lines if requested
    work_df = df.copy()
    if mask_straight_lines and "is_straight_line" in df.columns:
        work_df.loc[work_df["is_straight_line"], response_col] = np.nan
    
    def _detect_ip_for_group(group_df):
        """Detect stimulus-linked patterns for a single participant-session group."""
        # Get unique stimuli in order
        stim_orders = sorted(group_df[stim_col].unique())
        n_stim = len(stim_orders)
        
        if n_stim < stim_ip_thresh:
            return [], []
        
        # Get scales (consistent order)
        scales = sorted(group_df[scale_col].unique())
        
        # Build response vectors for each stimulus
        # response_vectors[stim_order] = tuple of responses in scale order (or None if any missing)
        response_vectors = {}
        stim_indices = {}  # stim_order -> list of original indices for that stimulus
        
        for stim_order in stim_orders:
            stim_data = group_df[group_df[stim_col] == stim_order]
            stim_indices[stim_order] = stim_data.index.tolist()
            
            # Build response vector in consistent scale order
            resp_dict = dict(zip(stim_data[scale_col], stim_data[response_col]))
            
            # Check if all scales present and no NaN
            if len(resp_dict) == len(scales) and all(not pd.isna(resp_dict.get(s)) for s in scales):
                response_vectors[stim_order] = tuple(resp_dict[s] for s in scales)
            else:
                response_vectors[stim_order] = None  # Mark as invalid (missing or NaN)
        
        # Find runs of identical response vectors
        flagged_indices = []
        run_lengths = {}  # index -> run_length
        
        i = 0
        while i < n_stim:
            stim_i = stim_orders[i]
            vec_i = response_vectors[stim_i]
            
            # Skip if invalid vector
            if vec_i is None:
                i += 1
                continue
            
            # Find end of run of identical vectors
            j = i + 1
            while j < n_stim:
                stim_j = stim_orders[j]
                vec_j = response_vectors[stim_j]
                if vec_j is None or vec_j != vec_i:
                    break
                j += 1
            
            run_len = j - i  # Number of consecutive stimuli with identical vectors
            
            if run_len >= stim_ip_thresh:
                # Flag all trials for stimuli in this run
                for k in range(i, j):
                    stim_k = stim_orders[k]
                    for idx in stim_indices[stim_k]:
                        flagged_indices.append(idx)
                        run_lengths[idx] = run_len
            
            i = j
        
        return flagged_indices, run_lengths
    
    # Process each participant-session group
    all_flagged = []
    all_run_lengths = {}
    
    groups = list(work_df.groupby([id_col, session_col], sort=False))
    
    if _n_jobs == 1 or len(groups) == 0:
        for _, group_df in groups:
            flagged, run_lens = _detect_ip_for_group(group_df)
            all_flagged.extend(flagged)
            all_run_lengths.update(run_lens)
    else:
        results = Parallel(n_jobs=_n_jobs)(
            delayed(_detect_ip_for_group)(group_df) for _, group_df in groups
        )
        for flagged, run_lens in results:
            all_flagged.extend(flagged)
            all_run_lengths.update(run_lens)
    
    # Update original dataframe
    df.loc[all_flagged, "is_inattentive_pattern"] = True
    for idx, run_len in all_run_lengths.items():
        df.loc[idx, "ip_run_length"] = run_len
    
    return df


def summarize_inattentive_patterns(df: pd.DataFrame, stim_ip_thresh: int, id_col: str = "id") -> pd.DataFrame:
    """Summarize stimulus-linked pattern statistics per participant (at trial level)."""
    if "is_inattentive_pattern" not in df.columns:
        df = detect_inattentive_patterns(df, stim_ip_thresh=stim_ip_thresh)
    
