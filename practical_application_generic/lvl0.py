# The run log's record of the adjustment, {residual column: {scale: fit}} (empty when no residual is adjusted): the
# clean trials fitted (n), their mean age (the centre), the fitted slope and its p, whether the slope is applied, the
# slope applied (0 when it is not) and the method.
_age_adjustment = {}
_finite_or_none = lambda v: None if v is None or not np.isfinite(v) else float(v)

if age_adjust_drift_residuals and 'age' in full_df.columns:
    print("\n[Age Adj] Removing linear age trend from drift residuals...")
    _age_res_cols = [f'drift_residual_{_t}_{_b}' for _t in ('raw', 'log', 'bc')
                                                  for _b in ('overall', 'per_ses')]
    for _res_col in _age_res_cols:
        # Fit age regression on CLEAN data only, then apply same slope to both
        _age_slopes = {}  # {scale_or_None: (slope, mean_age)}
        _age_adjustment[_res_col] = {}
        _scales = clean_df['scale'].dropna().unique()
        for _sc in _scales:
            _mask_c = clean_df['scale'] == _sc
            _sub = clean_df.loc[_mask_c, ['age', _res_col]].dropna()
            if len(_sub) < 10:
                _age_adjustment[_res_col][_sc] = {"n": int(len(_sub)), "mean_age": None, "slope": None, "p": None,
                                                  "applied": False, "applied_slope": 0.0,
                                                  "method": "not fitted (fewer than 10 clean trials)"}
                continue
            _mean_age = float(_sub['age'].mean())
            # Significance gate (p<0.10): apply slope only when the
            # age-residual relationship is at least suggestive. Avoids
            # injecting noise from imprecisely-estimated slopes in small
            # per-scale subsets.
            try:
                from scipy import stats as _stats_age
                _lr = _stats_age.linregress(_sub['age'].values - _mean_age,
                                            _sub[_res_col].values)
                _age_gate = np.isfinite(_lr.pvalue) and _lr.pvalue < 0.10
                _slope_val = float(_lr.slope) if _age_gate else 0.0
                _age_fit = (_lr.slope, _lr.pvalue, bool(_age_gate), "linregress (slope applied when p < 0.10)")
            except Exception:
                _b = np.polyfit(_sub['age'] - _mean_age, _sub[_res_col], 1)
                _slope_val = float(_b[0])
                _age_fit = (_b[0], None, True, "polyfit (no p; slope applied)")
            _age_slopes[_sc] = (_slope_val, _mean_age)
            _age_adjustment[_res_col][_sc] = {"n": int(len(_sub)), "mean_age": _mean_age,
                                              "slope": _finite_or_none(_age_fit[0]), "p": _finite_or_none(_age_fit[1]),
                                              "applied": _age_fit[2], "applied_slope": _slope_val, "method": _age_fit[3]}
        # Apply the clean-data slope to both DataFrames
        for _df in [full_df, clean_df]:
            _out_col = _res_col + '_age'
            _df[_out_col] = _df[_res_col].copy()
            for _sc in _scales:
                if _sc not in _age_slopes:
                    continue
                _slope, _mean_age = _age_slopes[_sc]
                _mask = _df['scale'] == _sc
                # Remove age slope, preserve sample mean (center age so intercept = mean)
                _valid = _mask & _df['age'].notna()
                _df.loc[_valid, _out_col] = (
                    _df.loc[_valid, _res_col] - _slope * (_df.loc[_valid, 'age'] - _mean_age)
                )
        print(f"  Created {_res_col}_age (per scale)")
