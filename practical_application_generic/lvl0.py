# -----------------------------------------------------------------------------
# check_input_data reads the raw data and changes nothing. It stops, listing up to 20 offending rows per rule, when
# the data break a rule of the format or LVL_0_CONFIG's age settings do not fit them. response codes are checked
# against LVL_1_CONFIG's scale_ranges at LVL_1, the scale names against its keys.
REQUIRED_COLUMNS = ("id", "condition", "session", "scale", "stim_order", "resp_order", "stim_label", "response",
                    "rt_sec")


def check_input_data(df, config):
    """Stop unless `df`, the raw long-format data, has the format of the README's "Data format" and `config`
    (LVL_0_CONFIG) fits it. Every broken rule is listed with its count and up to 20 offending rows (row = the 0-based
    data row of the file; file line = row + 2)."""
    missing = [c for c in REQUIRED_COLUMNS if c not in df.columns]
    if missing:
        raise SystemExit(f'input check ({INPUT_LONG_PATH.name}): required column(s) {missing} missing; the file has '
                         f'{list(df.columns)} (README, "Data format")')
    broken = []

    def rule(text, rows, n=None, unit="rows"):
        """Record a broken rule: `rows` are the offending rows (or one row per offending id), n their count in unit."""
        if len(rows):
            broken.append(f"  - {text} ({unit}: {len(rows) if n is None else n:,})\n" + "\n".join(
                "        " + ln for ln in rows.head(20).to_string().splitlines()))

    def where_values(c, test):
        """The rows whose value of column c passes test, decided once per distinct value."""
        u = pd.Series(pd.unique(df[c]), dtype=object)
        return df[c].isin(u[test(u).to_numpy(bool)])

    _text = lambda u: u.map(lambda v: isinstance(v, str) and v.strip() != "")
    _whole = lambda v: v.notna() & (v % 1 == 0)
    num = {c: pd.to_numeric(df[c], errors="coerce") for c in ("id", "session", "stim_order", "resp_order", "response",
                                                               "rt_sec")}
    ok = {c: _whole(num[c]) for c in ("id", "session", "resp_order")}
    ok["stim_order"] = _whole(num["stim_order"]) & (num["stim_order"] >= 1)
    for c, show in (("id", ["id"]), ("session", ["id", "session"]), ("resp_order", ["id", "session", "resp_order"])):
        rule(f"{c}: a whole number in every row", df.loc[~ok[c], show])
    rule("stim_order: a whole number >= 1 in every row", df.loc[~ok["stim_order"], ["id", "session", "stim_order"]])
    rule('condition: non-numeric text in every row (e.g. "A")',
         df.loc[~where_values("condition", lambda u: _text(u) & pd.to_numeric(u, errors="coerce").isna()),
                ["id", "condition"]])
    rule("scale: text in every row", df.loc[~where_values("scale", _text), ["id", "session", "stim_order", "scale"]])
    rule("stim_label: a value in every row", df.loc[df["stim_label"].isna(), ["id", "session", "stim_order", "scale"]])
    rule("response: a whole number where present (missing allowed)",
         df.loc[df["response"].notna() & ~_whole(num["response"]), ["id", "session", "scale", "response"]])
    rule("rt_sec: a number > 0 where present (missing allowed)",
         df.loc[df["rt_sec"].notna() & ~(num["rt_sec"] > 0), ["id", "session", "scale", "rt_sec"]])
    if "age" in df.columns:
        rule("age (optional column): a number in every row (without ages, leave the column out)",
             df.loc[pd.to_numeric(df["age"], errors="coerce").isna(), ["id", "age"]])

    # The rules over a participant or a stimulus, on the rows whose keys passed the rules above.
    d = df.loc[ok["id"] & ok["session"] & ok["stim_order"] & ok["resp_order"],
               [c for c in ("id", "condition", "session", "scale", "stim_order", "resp_order", "stim_label", "age")
                if c in df.columns]]
    _stim = ["id", "session", "stim_order"]
    _n = d.groupby("id")["condition"].nunique()
    rule("id: one condition per id", d.loc[d["id"].isin(_n.index[_n > 1]), ["id", "condition"]].drop_duplicates(),
         int((_n > 1).sum()), "ids")
    if "age" in d.columns:                 # over the numeric ages (a non-numeric age is reported by the rule above)
        _age = pd.to_numeric(d["age"], errors="coerce")
        _n = _age.groupby(d["id"]).nunique()
        rule("age: constant within id",
             d.loc[d["id"].isin(_n.index[_n > 1]) & _age.notna(), ["id", "age"]].drop_duplicates(),
             int((_n > 1).sum()), "ids")
    _dup = d.duplicated(_stim + ["scale"], keep=False)
    rule("scale: one row per stimulus x scale (id, session, stim_order, scale)",
         d.loc[_dup, _stim + ["scale", "resp_order"]].sort_values(_stim + ["scale"]))
    _n = d.groupby(_stim)["stim_label"].transform("nunique")
    rule("stim_label: the same on every scale row of a stimulus", d.loc[_n > 1, _stim + ["scale", "stim_label"]],
         len(d.loc[_n > 1, _stim].drop_duplicates()), "stimuli")
    # Fixed scale order: within a participant-session the scales of every stimulus, in resp_order, follow the order of
    # the session's most frequent complete stimulus (a stimulus may lack a scale row).
    s = d.loc[~_dup].sort_values(_stim + ["resp_order"], kind="mergesort")
    _seq = s.groupby(_stim, sort=False)["scale"].agg(tuple)
    _n = s.groupby(["id", "session"])["scale"].nunique()
    _full = _seq[_seq.map(len).to_numpy() == _n.reindex(_seq.index.droplevel(2)).to_numpy()]
    if len(_full):
        _ref = _full.groupby(level=[0, 1]).agg(lambda x: x.value_counts().index[0])
        _rank = pd.DataFrame([(i, ses, sc, r) for (i, ses), order in _ref.items() for r, sc in enumerate(order)],
                             columns=["id", "session", "scale", "rank"])
        _r = pd.Series(s[["id", "session", "scale"]].merge(_rank, how="left")["rank"].to_numpy(), index=s.index)
        _prev = _r.shift()
        _bad = (s[_stim] == s[_stim].shift()).all(axis=1) & _r.notna() & _prev.notna() & ~(_r > _prev)
        _bad = _bad.groupby([s[c] for c in _stim]).transform("any")
        rule("scale: the scales of every stimulus in one order within a participant-session (by resp_order)",
             s.loc[_bad, _stim + ["resp_order", "scale"]], len(s.loc[_bad, _stim].drop_duplicates()), "stimuli")

    # LVL_0_CONFIG: the types of the age settings, the RT limits and pr_stim_drop, the intake lists, and the age settings
    # without an age column.
    _number = lambda v: v is None or (isinstance(v, (int, float, np.integer, np.floating)) and not isinstance(v, bool))
    broken += [f"  - LVL_0_CONFIG[{k!r}] = {config[k]!r}: a number (years) or None"
               for k in ("max_age", "age_group_split") if not _number(config[k])]
    if not isinstance(config["age_adjust_drift_residuals"], (bool, np.bool_)):
        broken.append(f"  - LVL_0_CONFIG['age_adjust_drift_residuals'] = {config['age_adjust_drift_residuals']!r}: "
                      "True or False")
    broken += [f"  - LVL_0_CONFIG[{k!r}] = {config[k]!r}: a number of seconds, 0 = off"
               for k in ("max_rt_thresh", "min_rt_thresh") if config[k] is None or not (_number(config[k]) and config[k] >= 0)]
    if isinstance(config["pr_stim_drop"], bool) or not isinstance(config["pr_stim_drop"], (int, np.integer)) \
            or config["pr_stim_drop"] < 0:
        broken.append(f"  - LVL_0_CONFIG['pr_stim_drop'] = {config['pr_stim_drop']!r}: a whole number of stimuli, 0 = none")
    broken += [f'  - LVL_0_CONFIG[{k!r}] = {config[k]!r}: "all" or a list' for k in ("sessions", "conditions")
               if not (isinstance(config[k], (list, tuple)) or config[k] == "all")]
    if "age" not in df.columns:
        broken += [f"  - LVL_0_CONFIG[{k!r}] = {config[k]!r}: the data have no age column, so it must be {v!r}"
                   for k, v in (("max_age", None), ("age_group_split", None), ("age_adjust_drift_residuals", False))
                   if config[k] is not v]
    if broken:
        raise SystemExit(f'input check ({INPUT_LONG_PATH.name}): {len(broken)} rule(s) broken. Fix the data file or '
                         'LVL_0_CONFIG ([cell 3]), then run again (README, "Data format"; row = the 0-based data row, '
                         'file line = row + 2):\n' + "\n".join(broken))
    print(f"input check ({INPUT_LONG_PATH.name}): {len(df):,} rows, {df['id'].nunique()} participants; the format "
          "holds")

# ---------------------------------------------------------------- knob overrides
