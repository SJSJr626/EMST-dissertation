def model_exp_fatigue(trial: np.ndarray, asymptote: float, amplitude: float, 
                      rate: float, fatigue: float) -> np.ndarray:
    """
    Exponential decay with linear fatigue term.
    RT(t) = asymptote + amplitude * exp(-rate * t) + fatigue * t
    """
    trial = np.asarray(trial, dtype=float)
    return asymptote + amplitude * np.exp(-rate * trial) + fatigue * trial
def model_exp(trial: np.ndarray, asymptote: float, amplitude: float, 
              rate: float) -> np.ndarray:
    """
    Simple exponential decay (no fatigue term).
    RT(t) = asymptote + amplitude * exp(-rate * t)
    """
    trial = np.asarray(trial, dtype=float)
    return asymptote + amplitude * np.exp(-rate * trial)

def model_log_decay(trial: np.ndarray, asymptote: float, amplitude: float,
                    rate: float) -> np.ndarray:
    """
    Logarithmic decay.
    RT(t) = asymptote + amplitude / (log(1 + rate * (t + 1)) + epsilon)
    where epsilon = 1e-10 prevents division-by-zero, and the (t + 1) shift
    moves the singularity at t=0 outside the valid trial range so the model
    can be safely evaluated on trials below the curve-fit window
    (e.g. dropped practice trials retained for downstream use).

    Slower decay than exponential, common in learning/practice literature.
    Note: When rate*(t+1) is small, this approximates 1/(rate*(t+1)),
    giving hyperbolic-like behavior.
    """
    trial = np.asarray(trial, dtype=float)
    return asymptote + amplitude / (np.log1p(rate * (trial + 1)) + 1e-10)

def model_log_fatigue(trial: np.ndarray, asymptote: float, amplitude: float,
                      rate: float, fatigue: float) -> np.ndarray:
    """
    Logarithmic decay with linear fatigue term.
    RT(t) = asymptote + amplitude / (log(1 + rate * (t + 1)) + epsilon) + fatigue * t
    where epsilon = 1e-10 prevents division-by-zero, and the (t + 1) shift
    in the log term moves the singularity at t=0 outside the valid trial range.
    Fatigue is kept as a function of raw t (no shift), so a 0-trial baseline
    contributes 0 fatigue.

    Combines slower-than-exponential log decay with linear fatigue accumulation.
    """
    trial = np.asarray(trial, dtype=float)
    return asymptote + amplitude / (np.log1p(rate * (trial + 1)) + 1e-10) + fatigue * trial

def model_linear(trial: np.ndarray, intercept: float, slope: float) -> np.ndarray:
    """
    Simple linear decay.
    RT(t) = intercept + slope * t
    """
    trial = np.asarray(trial, dtype=float)
    return intercept + slope * trial

