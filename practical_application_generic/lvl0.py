    ax.hist(all_null_values, bins=bins, density=True, alpha=0.7, color="steelblue", 
            edgecolor="black", label="Null distribution (pooled)")
    
    # Mark percentiles of the pooled null
    colors = ["orange", "red", "darkred"]
    suggested_thresholds = {}
    for i, pct in enumerate(percentiles):
        thresh = np.percentile(all_null_values, pct)
        suggested_thresholds[pct] = int(np.ceil(thresh))
        ax.axvline(thresh, color=colors[i % len(colors)], linestyle="--", linewidth=2,
                   label=f"{pct}th percentile: {thresh:.1f}")
    
    if current_thresh is not None:
        ax.axvline(current_thresh, color="green", linestyle="-", linewidth=2,
                   label=f"Current threshold: {current_thresh}")
    
    ax.set_xlabel(f"Max Run Length ({detection_type})")
    ax.set_ylabel("Density")
    ax.set_title(f"{detection_type}: Null Distribution (pooled, {len(all_null_values):,} samples)")
    ax.legend(loc="upper right")
    
    # Right: Distribution of observed max runs
    ax = axes[1]
    
    bins = np.arange(0, observed_global_max + 2) - 0.5
    ax.hist(observed_values, bins=bins, alpha=0.7, color="mediumpurple", 
            edgecolor="black", label="Observed (per participant-session)")
    
    # Mark thresholds
    for i, pct in enumerate(percentiles):
        thresh = suggested_thresholds[pct]
        ax.axvline(thresh, color=colors[i % len(colors)], linestyle="--", linewidth=2,
                   label=f"{pct}th pct null: {thresh}")
    
    if current_thresh is not None:
        ax.axvline(current_thresh, color="green", linestyle="-", linewidth=2,
                   label=f"Current threshold: {current_thresh}")
    
    n_total = len(observed_values)
    ax.set_xlabel(f"Max Run Length ({detection_type})")
    ax.set_ylabel("Number of Participant-Sessions")
    ax.set_title(f"{detection_type}: Observed Max Runs (n={n_total} participant-sessions)")
    ax.legend(loc="upper right")
    
    plt.tight_layout()
    
    # Print summary
    print("=" * 70)
    print(f"{detection_type.upper()} THRESHOLD ANALYSIS")
    print("=" * 70)
    print(f"Null distribution (pooled from {n_total} participant-sessions x permutations):")
    print(f"  Mean max run by chance: {all_null_values.mean():.1f}")
    print(f"  Median max run by chance: {np.median(all_null_values):.1f}")
    print(f"  Max observed in null: {all_null_values.max():.0f}")
    print("-" * 70)
    print("Null percentile markers (pooled over these participant-sessions):")
    for pct in percentiles:
        thresh = suggested_thresholds[pct]
        n_exceed = np.sum(observed_values >= thresh)
        pct_exceed = 100 * n_exceed / n_total if n_total > 0 else 0
        print(f"  {pct}th percentile: {thresh} ({n_exceed} participant-sessions exceed, {pct_exceed:.1f}%)")
    print("-" * 70)
    print(f"Observed data:")
    print(f"  Global max run: {observed_global_max}")
    print(f"  Mean max run per participant-session: {np.mean(observed_values):.1f}")
    print(f"  Median max run per participant-session: {np.median(observed_values):.1f}")
    if current_thresh is not None:
        n_exceed_current = np.sum(observed_values >= current_thresh)
        pct_exceed_current = 100 * n_exceed_current / n_total if n_total > 0 else 0
        print(f"  Exceeding current threshold ({current_thresh}): {n_exceed_current} ({pct_exceed_current:.1f}%)")
    
    # How many participants have observed values exceeding their own 95th/99th percentile null?
    print("-" * 70)
    print("Per-participant analysis (observed vs own null):")
    for pct_thresh in [95, 99]:
        n_exceed_own = sum(1 for p in observed_percentiles if p >= pct_thresh)
