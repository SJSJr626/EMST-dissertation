# Lazy rpy2 import so the notebook works even without rpy2/R installed as
# long as merge_method != "robust_tost".

def _run_wilcox_tost(x, y, equiv_bound, alpha):
    """
    Call TOSTER::wilcox_TOST via rpy2.

    Equivalence bounds are in SMD (Cohen's d) units so they are
    scale-invariant across different merged features.

    Returns
    -------
    float
        TOST p-value = max(p_lower, p_upper).  The *max* is used because
        equivalence requires BOTH one-sided tests to be significant; the
        larger p-value is the binding constraint.
        p < alpha  →  equivalence established.
    """
    from rpy2.robjects import FloatVector
    import rpy2.robjects.packages as rpackages

    TOSTER = rpackages.importr('TOSTER')

    x_r = FloatVector(x.tolist())
    y_r = FloatVector(y.tolist())

    r_result = TOSTER.wilcox_TOST(
        x_r,
        y_r,
        low_eqbound  = -equiv_bound,
        high_eqbound =  equiv_bound,
        eqbound_type = "SMD",
        paired       = False,
        alpha        = alpha,
    )

    # TOSTER::wilcox_TOST returns an R list whose $TOST element is a data
    # frame with rows = (lower-bound test, upper-bound test) and a p.value
    # column. rpy2 here uses R-style 1-indexed access on the R DataFrame:
    #   rx2('TOST')[1]   -> the p.value column
    #   col[1], col[2]   -> rows 1 and 2 of that column
    # Indices depend on TOSTER's $TOST column order; revalidate if you
    # upgrade the R package.
    tost_col  = r_result.rx2('TOST')[1]   # p.value column
    p_lower   = float(tost_col[1])        # lower one-sided p
    p_upper   = float(tost_col[2])        # upper one-sided p
    return max(p_lower, p_upper)          # binding constraint (TOST conclusion)


def compute_pair_merge_score(features, mask_a, mask_b, feature_cols, config, merge_on):
    """
    Compute merge score for a pair of adjacent blocks.

    Higher score = more appropriate to merge.

    merge_method logic
    ------------------
    "ttest"      : merge when blocks are NOT significantly different (Welch t-test).
                   Qualifies when n_significant < merge_on  (fewer diffs → merge).
    "wilcoxon"   : same logic as ttest but uses Mann-Whitney U (rank-based, no
                   normality assumption). Better for bounded/skewed features like
                   Entropy. Qualifies when n_significant < merge_on.
    "robust_tost": merge when blocks ARE statistically equivalent via Wilcoxon
                   TOST (TOSTER R package, bounds in SMD units).
                   Qualifies when n_equivalent >= merge_on  (more equiv → merge).

    Returns
    -------
    score : float
        Merge score (higher = better candidate for merging)
    qualifies : bool
        Whether this pair meets the config merge criteria
    details : dict
        Per-feature statistics
    """
    merge_method  = config["merge_method"]
    merge_alpha   = config["merge_alpha"]
    equiv_bound   = config["merge_equivalence_bound"]

    p_values        = []
    equiv_scores    = []
    tested_features = []

    for col in feature_cols:
        values_a = features.loc[mask_a, col].dropna().values
        values_b = features.loc[mask_b, col].dropna().values

        if len(values_a) < 2 or len(values_b) < 2:
            continue

        tested_features.append(col)

        if merge_method == "ttest":
            # Welch t-test — higher p = less different = better for merging
            try:
                _, p_val = stats.ttest_ind(values_a, values_b, equal_var=False)
                p_values.append(float(p_val))
                equiv_scores.append(float(p_val))
            except Exception as _e_h6a:
                # surface the failure rather than swallowing silently.
                import warnings as _w_h6a
                _w_h6a.warn(
                    f"compute_pair_merge_score (ttest): {type(_e_h6a).__name__}: {_e_h6a}; using p=1.0",
                    stacklevel=2,
                )
                p_values.append(1.0)
                equiv_scores.append(1.0)

        elif merge_method == "wilcoxon":
            # Mann-Whitney U (Wilcoxon rank-sum) — non-parametric alternative to ttest.
            # Same merge logic: higher p = less different = better for merging.
            # Recommended for bounded/skewed features (e.g. Entropy, Rating Variance).
            try:
                _, p_val = stats.mannwhitneyu(values_a, values_b, alternative="two-sided")
                p_values.append(float(p_val))
                equiv_scores.append(float(p_val))
            except Exception as _e_h6b:
                # surface the failure rather than swallowing silently.
                import warnings as _w_h6b
                _w_h6b.warn(
                    f"compute_pair_merge_score (wilcoxon): {type(_e_h6b).__name__}: {_e_h6b}; using p=1.0",
                    stacklevel=2,
                )
                p_values.append(1.0)
                equiv_scores.append(1.0)

        elif merge_method == "robust_tost":
            # Wilcoxon TOST via TOSTER (R).  Bounds in SMD (Cohen's d) units.
            # p_tost = max(p_lower, p_upper) — binding constraint.
            # p_tost < alpha  →  equivalence established.
            try:
                p_tost = _run_wilcox_tost(values_a, values_b, equiv_bound, merge_alpha)
                p_values.append(float(p_tost))
                equiv_scores.append(1.0 - float(p_tost))   # higher = more equivalent
            except Exception as e:
                # Conservative: treat as NOT equivalent
                p_values.append(1.0)
                equiv_scores.append(0.0)

    if len(p_values) == 0:
        return -np.inf, False, {}

    merge_fdr = config['merge_fdr']

    # Apply FDR correction (or not) to the per-feature p-values
    if merge_fdr is None:
        # No correction — recommended for robust_tost
        p_fdr = p_values
    else:
        # 'per_pair' or 'global' (global treated as per_pair in greedy context)
        _, p_fdr = fdrcorrection(p_values, alpha=merge_alpha)
        p_fdr = list(p_fdr)

    if merge_method in ("ttest", "wilcoxon"):
        # Merge when few features are significantly DIFFERENT
        n_significant = int(sum(p < merge_alpha for p in p_fdr))
        n_equivalent  = None
        qualifies     = n_significant < merge_on
        score         = float(np.mean(p_fdr))           # higher p = more similar

    else:  # robust_tost
        # Merge when enough features show equivalence (p_tost < alpha)
        n_equivalent  = int(sum(p < merge_alpha for p in p_fdr))
        n_significant = None
        qualifies     = n_equivalent >= merge_on
        score         = float(np.mean(equiv_scores))    # higher score = more equivalent

    details = {
        "p_values":        p_values,
        "p_fdr":           list(p_fdr),
        "equiv_scores":    equiv_scores,
        "features_tested": tested_features,
        "n_significant":   n_significant,
        "n_equivalent":    n_equivalent,
    }

    return score, qualifies, details


def merge_nonsignificant_blocks(features, blocks, config, merge_features):
    """
    Merge adjacent blocks using greedy best-pair-first strategy.
    
    At each iteration, finds the most equivalent (or least different) adjacent
    pair that qualifies for merging, and merges that pair. Repeats until no
    more pairs qualify.
    
    Parameters
    ----------
    features : pd.DataFrame
        Trial-level features
    blocks : np.ndarray
        Initial block assignments (0-indexed)
    config : dict
        Configuration with:
        - merge_blocks: Enable/disable merging
        - merge_method: "ttest" | "wilcoxon" | "robust_tost"
        - merge_alpha: Significance threshold
        - merge_on: ttest       — max n_significant to ALLOW merge (fewer diffs → merge)
                    robust_tost — min n_equivalent to ALLOW merge (more equiv → merge)
        - merge_equivalence_bound: TOST bound in Cohen's d — used only with robust_tost
        - merge_fdr: FDR correction of the per-feature p-values within a pair
                     (None | "per_pair"; "global" is treated as "per_pair")
    
    Returns
    -------
    np.ndarray
        Merged block assignments
    """
    if not config["merge_blocks"]:
        return blocks

    merge_features = list(merge_features)
    merge_method = config["merge_method"]

    if not merge_features:
        return blocks
    
    # merge_on applies to MULTIVARIATE methods only. A univariate detector merges
    # when its single feature is non-significant, i.e. merge_on == 1 by construction.
    if len(merge_features) == 1:
        merge_on = 1
    else:
        merge_on = int(config["merge_on"])
        if merge_on < 1:
            raise ValueError(f"merge_on must be >= 1, got {merge_on}")
        if merge_on > len(merge_features):
            raise ValueError(
                f"merge_on ({merge_on}) cannot exceed the number of detection features "
                f"for this multivariate method ({len(merge_features)}: {merge_features})."
            )
    
    # Get validation map to translate feature names to columns
    validation_map = get_validation_map(config)
    
    # Get actual column names for merge features
    feature_cols = []
    for feat_name in merge_features:
        if feat_name in validation_map:
            col_name = validation_map[feat_name][0]
            if col_name in features.columns:
                feature_cols.append(col_name)
    
    if not feature_cols:
        print(f"[Merge] WARNING: No merge feature columns found in features df. "
              f"Requested: {merge_features}. Skipping merge.")
        return blocks

    print(f"[Merge] method={merge_method}, merge_on={merge_on}, alpha={config['merge_alpha']}, "
          f"features={feature_cols}")

    blocks = np.array(blocks).copy()

    # pre-merge contiguity normalization. CPD upstream may have
    # reordered block labels by signal magnitude, leaving the same label in
    # multiple separated temporal regions. Relabel each contiguous run with a
    # fresh ID so that any subsequent label-based merge fuses exactly the
    # two adjacent regions found in spatial_pairs (no aliasing across gaps).
    blocks = np.asarray(blocks).copy()
    if len(blocks) > 0:
        _new_blocks = np.zeros(len(blocks), dtype=int)
        _curr = 0
        _new_blocks[0] = 0
        for _i in range(1, len(blocks)):
            if blocks[_i] != blocks[_i - 1]:
                _curr += 1
            _new_blocks[_i] = _curr
        if not np.array_equal(_new_blocks, blocks):
            print(
                f"  [Merge pre-check] Relabelled {int(np.unique(blocks).size)} "
                f"original blocks → {_curr + 1} contiguous regions before merging."
            )
        blocks = _new_blocks
    
    # Greedy best-pair-first merging
    max_iterations = 100
    
    for iteration in range(max_iterations):
        unique_blocks = sorted(np.unique(blocks))
        
        if len(unique_blocks) < 2:
            break
        
        # Build spatially-adjacent pairs from actual block sequence
        # (block IDs may be reordered by signal level, so consecutive IDs
        #  are NOT necessarily spatially adjacent)
        spatial_pairs = []
        for i in range(len(blocks) - 1):
            if blocks[i] != blocks[i + 1]:
                pair = (blocks[i], blocks[i + 1])
                if pair not in spatial_pairs:
                    spatial_pairs.append(pair)
        
        # Evaluate ALL spatially adjacent pairs
        pair_scores = []
        
        for block_a, block_b in spatial_pairs:
            
            mask_a = blocks == block_a
            mask_b = blocks == block_b
            
            if mask_a.sum() < 3 or mask_b.sum() < 3:
                continue
            
            score, qualifies, details = compute_pair_merge_score(
                features, mask_a, mask_b, feature_cols, config, merge_on
            )
            
            if qualifies:
                pair_scores.append({
                    "block_a": block_a,
                    "block_b": block_b,
                    "score": score,
                    "details": details,
                })
        
        if not pair_scores:
            # No pairs qualify for merging
            break
        
        # Find the best pair (highest score = most equivalent / least different)
        best_pair = max(pair_scores, key=lambda x: x["score"])
        
        # Merge best pair (right into left)
        n_qual = len(pair_scores)
        print(f"  [Merge iter {iteration+1}] block {best_pair['block_a']}+{best_pair['block_b']} "
              f"(score={best_pair['score']:.3f}, {n_qual} qualifying pairs)")
        blocks[blocks == best_pair["block_b"]] = best_pair["block_a"]
    
    # Renumber blocks sequentially
    unique_blocks = sorted(np.unique(blocks))
    block_map = {old: new for new, old in enumerate(unique_blocks)}
    blocks = np.array([block_map[b] for b in blocks])
    
    return blocks

