# RT-THRESHOLD MISSINGNESS (Level-1 only): rt_threshold_na_handling
# =============================================================================
# A scale-level rating is REJECTED when its RT actually violates min_rt_thresh or
# max_rt_thresh (a threshold of 0 is off, as in apply_rt_filters). The knob decides how
# that rejection reaches the Level-1 RT features; see LVL_1_CONFIG (cell 9):
#   partial        the rejected scale's RT values are removed; the stimulus averages the
#                  remaining scales, and that scale's rolling variance there is NaN.
#   drop_stimulus  the whole stimulus is invalid: all of its per-scale inputs are removed
#                  before the features are built (so it enters no neighbour's window),
#                  and every derived feature at that stimulus is NaN.
#   bfill / ffill  the rejected scale's RT values are filled from the next / previous
#                  valid value of the same scale in the same session (fill_rejected).
#                  That scale's rolling variance at the stimulus is its window's variance
#                  of the remaining valid values; only when fewer than min_periods
#                  remain is it filled the same way (never in a rolling-window edge).
# In every mode the rejected RT enters no rolling window. Only rejected cells are ever
# written: window edges, practice stimuli and naturally missing values are untouched.
# Entropy keeps the row-level filter (apply_rt_filters already NaNs the rejected
# rating's response) except under drop_stimulus, which removes the whole stimulus.
# The per-scale pass-through columns ({scale}_response, {scale}_rt_input, ...) keep
# the row-level filter only in every mode, because LVL_2 reads them from the handoff.
_STIM_INPUT_SUFFIXES = ("_rt", "_response", "_predicted", "_residual", "_residual_abs", "_rt_input")
# The per-scale RT observations the Level-1 RT features are built from. {scale}_predicted
# is the drift model's prediction (not an observation, and unused by the features): it
# keeps the row-level filter only.
_RT_OBS_SUFFIXES = ("_rt", "_residual", "_residual_abs")
# Derived columns that are NOT per-stimulus measurements and stay as computed.
_KEEP_DERIVED = {"trial_global", "trial_in_session", "session_indicator",
                 "global_rt_var", "global_residual_var"}
_STIM_KEYS = ["id", "session", "stim_order"]


def rt_threshold_rejections(long_rows, config):
    """Scale-level ratings rejected by min_rt_thresh / max_rt_thresh: a boolean frame
    indexed by (id, session, stim_order), one column per scale. Read from
    rt_sec_prefilter, the untouched copy cell 20 keeps before apply_rt_filters NaNs
    rt_sec. A missing RT is not a rejection; nor is a practice stimulus (pr_stim_drop
    removes it, not an RT threshold)."""
    if "rt_sec_prefilter" not in long_rows.columns:
        raise SystemExit("rt_threshold_rejections: rt_sec_prefilter missing; "
                         "cell 20 must snapshot rt_sec before apply_rt_filters.")
    rt = pd.to_numeric(long_rows["rt_sec_prefilter"], errors="coerce")
    rej = pd.Series(False, index=long_rows.index)
    if config["max_rt_thresh"] > 0:
        rej |= rt > config["max_rt_thresh"]
    if config["min_rt_thresh"] > 0:
        rej |= rt < config["min_rt_thresh"]
    if config["pr_stim_drop"] > 0:
        rej &= long_rows["stim_order"] > config["pr_stim_drop"]
    scales = list(config["scale_ranges"].keys())
    return (long_rows[_STIM_KEYS + ["scale"]].assign(_rej=rej.to_numpy())
            .groupby(_STIM_KEYS + ["scale"])["_rej"].any()
            .unstack("scale", fill_value=False)
            .reindex(columns=scales, fill_value=False).astype(bool))


def level1_features(stim_lvl_df, rejected, config):
    """compute_stim_resp_features with the rt_threshold_na_handling rule applied.
    `rejected` is rt_threshold_rejections() for the same rows."""
    mode = rt_threshold_na_mode(config)
    scales = list(config["scale_ranges"].keys())
    rej = pd.DataFrame(
        rejected.reindex(pd.MultiIndex.from_frame(stim_lvl_df[_STIM_KEYS]), fill_value=False)
                .reindex(columns=scales, fill_value=False).to_numpy(dtype=bool),
        index=stim_lvl_df.index, columns=scales)
    n_rej = pd.Series(rej.sum(axis=1).to_numpy(), index=pd.MultiIndex.from_frame(stim_lvl_df[_STIM_KEYS]))

    if mode == "drop_stimulus":
        contaminated = set(stim_lvl_df.loc[rej.any(axis=1), "stim_order"].tolist())
        inputs = [f"{s}{x}" for s in scales for x in _STIM_INPUT_SUFFIXES
                  if f"{s}{x}" in stim_lvl_df.columns]
        hit = stim_lvl_df["stim_order"].isin(contaminated).to_numpy()
        masked = stim_lvl_df.copy()
        masked.loc[hit, inputs] = np.nan
        features = compute_stim_resp_features(masked, config)
        contam = features["stim_order"].isin(contaminated).to_numpy()
        if contam.any():
            # restore the row-filtered per-scale values handed to LVL_2
            raw = stim_lvl_df.set_index("stim_order")[inputs]
            features.loc[contam, inputs] = raw.loc[features.loc[contam, "stim_order"]].to_numpy()
            derived = [c for c in features.columns
                       if c not in stim_lvl_df.columns and c not in _KEEP_DERIVED]
            features.loc[contam, derived] = np.nan
    else:
        order = stim_lvl_df.sort_values(_STIM_KEYS, kind="stable").index
        base, rej = stim_lvl_df.loc[order].copy(), rej.loc[order]
        groups = [base[k].to_numpy() for k in ("id", "session")]
        obs = [(s, f"{s}{x}") for s in scales for x in _RT_OBS_SUFFIXES if f"{s}{x}" in base.columns]
        for s, col in obs:
            base.loc[rej[s], col] = np.nan
            if mode != "partial":
                base[col] = fill_rejected(base[col], rej[s], mode, groups=groups).to_numpy()
        features = compute_stim_resp_features(base, config, rt_rejected=rej,
                                              rt_rejected_fill=None if mode == "partial" else mode)
        # restore the row-filtered per-scale values handed to LVL_2 (as drop_stimulus does)
        cols = [c for _, c in obs]
        features[cols] = (stim_lvl_df.set_index(_STIM_KEYS)[cols]
                          .reindex(pd.MultiIndex.from_frame(features[_STIM_KEYS])).to_numpy())
        contam = np.zeros(len(features), dtype=bool)
    features["stim_rt_contaminated"] = contam      # True only where drop_stimulus removed the stimulus
    features["n_rt_rejected_scales"] = n_rej.reindex(
        pd.MultiIndex.from_frame(features[_STIM_KEYS])).to_numpy()
    return features


