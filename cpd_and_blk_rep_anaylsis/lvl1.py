def apply_rt_filters(df, max_rt_thresh, min_rt_thresh, pr_stim_drop,
                     rt_col="rt_sec", response_col="response", stim_col="stim_order", verbose=True):
    """
    Apply RT threshold and practice-stimulus filters by setting values to NaN.
    Preserves row structure (does not drop rows).

    Each threshold is its own gate: set it to 0 to disable that filter.

    Parameters
    ----------
    df : pd.DataFrame
        Long-format data
    max_rt_thresh : float
        Maximum acceptable RT; 0 disables the slow-RT filter
    min_rt_thresh : float
        Minimum acceptable RT; 0 disables the fast-RT filter
    pr_stim_drop : int
        Practice stimuli to NaN at session start; 0 disables the practice filter
    rt_col : str
        Name of RT column
    response_col : str
        Name of response column
    stim_col : str
        Name of stimulus-order column (default: "stim_order")
    verbose : bool
        Print filtering summary

    Returns
    -------
    pd.DataFrame
        Data with filtered values set to NaN
    """
    df = df.copy()

    n_total = len(df)
    n_max_filtered = 0
    n_min_filtered = 0
    n_ps_filtered = 0

    # Every RT-derived column must be NaN'd wherever the RT itself is: a trial the
    # level excluded must not survive in a derived column. `rt_input` is named
    # explicitly because it does not carry either prefix, and it is the ONLY RT
    # metric LVL_2 sees -- if it escaped filtering, LVL_2 would analyse trials LVL_1
    # had already thrown out.
    _resid_cols = [c for c in df.columns
                   if c.startswith(("predicted_rt", "drift_residual"))
                   or c == "rt_input"]

    # Filter RT > max_rt_thresh
    if max_rt_thresh > 0:
        mask_too_slow = df[rt_col] > max_rt_thresh
        n_max_filtered = mask_too_slow.sum()

        df.loc[mask_too_slow, rt_col] = np.nan
        df.loc[mask_too_slow, response_col] = np.nan
        df.loc[mask_too_slow, _resid_cols] = np.nan

    # Filter RT < min_rt_thresh
    if min_rt_thresh > 0:
        mask_too_fast = df[rt_col] < min_rt_thresh
        n_min_filtered = mask_too_fast.sum()

        df.loc[mask_too_fast, rt_col] = np.nan
        df.loc[mask_too_fast, response_col] = np.nan
        df.loc[mask_too_fast, _resid_cols] = np.nan

    # Filter responses to practice stimuli
    if pr_stim_drop > 0:
        mask_pract_stim = df[stim_col] <= pr_stim_drop
        n_ps_filtered = mask_pract_stim.sum()

        df.loc[mask_pract_stim, rt_col] = np.nan
        df.loc[mask_pract_stim, response_col] = np.nan
        df.loc[mask_pract_stim, _resid_cols] = np.nan

    if verbose:
        print("=" * 60)
        print("FILTERING SUMMARY")
        print("=" * 60)
        print(f"  max_rt_thresh  (>{max_rt_thresh}s):          {'ON' if max_rt_thresh > 0 else 'OFF'}")
        print(f"  min_rt_thresh  (<{min_rt_thresh}s):          {'ON' if min_rt_thresh > 0 else 'OFF'}")
        print(f"  pr_stim_drop   ({stim_col}<={pr_stim_drop}): {'ON' if pr_stim_drop > 0 else 'OFF'}")
        print("-" * 60)

        # counts can overlap (e.g. a too-slow practice trial counts twice),
        # so this is an upper bound on the number of distinct cells NaN'd.
        total_filtered = n_max_filtered + n_min_filtered + n_ps_filtered
        if total_filtered > 0 or max_rt_thresh > 0 or min_rt_thresh > 0 or pr_stim_drop > 0:
            print(f"  Slow RT (>{max_rt_thresh}s) set to NaN:      {n_max_filtered} ({100*n_max_filtered/n_total:.2f}%)")
            print(f"  Fast RT (<{min_rt_thresh}s) set to NaN:      {n_min_filtered} ({100*n_min_filtered/n_total:.2f}%)")
            print(f"  Practice stimuli set to NaN:                 {n_ps_filtered} ({100*n_ps_filtered/n_total:.2f}%)")
            print(f"  Total NaN'd (upper bound, overlaps possible):{total_filtered} ({100*total_filtered/n_total:.2f}%)")
        else:
            print("  No filtering applied (all thresholds 0)")
        print("=" * 60)

    return df


