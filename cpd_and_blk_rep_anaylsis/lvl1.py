def create_fixed_blocks_for_session(n_rows, n_blocks):
    """
    Create fixed-length block assignments for a session.
    
    Parameters
    ----------
    n_rows : int
        Number of rows in the session
    n_blocks : int
        Target number of blocks
    
    Returns
    -------
    np.ndarray
        Block assignments (0 to n_blocks-1)
        Longest block is at the end (for fatigue)
    """
    if n_blocks <= 0:
        return np.zeros(n_rows, dtype=int)
    
    if n_blocks >= n_rows:
        return np.arange(n_rows, dtype=int)
    
    # Calculate base block size and remainder
    base_size = n_rows // n_blocks
    remainder = n_rows % n_blocks
    
    # Create block assignments
    # Put extra rows in LAST blocks (longest at end for fatigue)
    blocks = []
    row_idx = 0
    
    for block_num in range(n_blocks):
        # Last 'remainder' blocks get one extra row
        if block_num >= (n_blocks - remainder):
            block_size = base_size + 1
        else:
            block_size = base_size
        
        blocks.extend([block_num] * block_size)
        row_idx += block_size
    
    return np.array(blocks, dtype=int)


def make_blocks_unique_per_participant(df, block_col, id_col='id', session_col='session'):
    """
    Make block IDs unique per participant instead of per session.
    
    E.g., if session 1 has blocks [0, 1, 2] and session 2 has blocks [0, 1, 2, 3],
    this function renumbers them to [0, 1, 2] and [3, 4, 5, 6] respectively.
    
    Parameters
    ----------
    df : pd.DataFrame
        DataFrame with block assignments
    block_col : str
        Name of the block column to renumber
    id_col : str
        Participant ID column
    session_col : str
        Session column
    
    Returns
    -------
    np.ndarray
        Renumbered block assignments unique per participant
    """
    new_blocks = []
    
    for pid in df[id_col].unique():
        pid_mask = df[id_col] == pid
        pid_data = df.loc[pid_mask].copy()
        sessions = sorted(pid_data[session_col].unique())
        
        block_offset = 0
        for sess in sessions:
            sess_mask = pid_data[session_col] == sess
            sess_blocks = pid_data.loc[sess_mask, block_col].values
            
            # Renumber blocks for this session
            renumbered = sess_blocks + block_offset
            new_blocks.extend(renumbered)
            
            # Update offset for next session
            block_offset = renumbered.max() + 1 if len(renumbered) > 0 else block_offset
    
    return np.array(new_blocks, dtype=int)


