# ENFORCE MINIMUM BLOCK LENGTH
# =============================================================================

def enforce_min_block_length(blocks, config):
    """
    Merge small blocks into neighbors until all blocks >= min_block_size.
    
    Parameters
    ----------
    blocks : array-like
        Block assignments
    config : dict
        Configuration dictionary (required)
    
    Returns
    -------
    np.ndarray
        Adjusted block assignments
    """
    min_len = config["min_block_size"]
    
    blocks = np.asarray(blocks)
    n = len(blocks)
    
    if n == 0:
        return blocks
    if n < min_len:
        return np.zeros(n, dtype=int)
    
    # Build contiguous segments
    segments = []
    start = 0
    for i in range(1, n):
        if blocks[i] != blocks[i - 1]:
            segments.append([start, i])
            start = i
    segments.append([start, n])
    
    # Iteratively merge until all segments >= min_len
    # hard cap at 2*n iterations — each iteration removes one
    # segment, and pathological inputs (e.g. min_len > n/2 with alternating
    # singletons) shouldn't loop indefinitely.
    _max_iter = 2 * n + 10
    _iter = 0
    while True:
        _iter += 1
        if _iter > _max_iter:
            import warnings as _w_m5
            _w_m5.warn(
                f"enforce_min_block_length: hit iteration cap {_max_iter}; returning current segments",
                stacklevel=2,
            )
            break
        lengths = np.array([end - beg for (beg, end) in segments], dtype=int)
        if len(lengths) == 0:
            break
        
        min_idx = int(np.argmin(lengths))
        smallest = int(lengths[min_idx])
        
        if smallest >= min_len:
            break
        if len(segments) == 1:
            break
        
        if min_idx == 0:
            merge_idx = 1
        elif min_idx == len(segments) - 1:
            merge_idx = len(segments) - 2
        else:
            left_len = segments[min_idx - 1][1] - segments[min_idx - 1][0]
            right_len = segments[min_idx + 1][1] - segments[min_idx + 1][0]
            merge_idx = min_idx - 1 if left_len <= right_len else min_idx + 1
        
        i1, i2 = sorted([min_idx, merge_idx])
        s1, e1 = segments[i1]
        s2, e2 = segments[i2]
        new_start = min(s1, s2)
        new_end = max(e1, e2)
        
        segments.pop(i2)
        segments.pop(i1)
        
        insert_pos = 0
        while insert_pos < len(segments) and segments[insert_pos][0] < new_start:
            insert_pos += 1
        segments.insert(insert_pos, [new_start, new_end])
    
    new_blocks = np.zeros(n, dtype=int)
    for bid, (beg, end) in enumerate(segments):
        new_blocks[beg:end] = bid
    
    return new_blocks

