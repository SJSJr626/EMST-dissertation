class KnobConstraintError(ValueError):
    """Illegal knob value or combination. Never caught internally."""

ODD_ONLY_KNOBS = ("smoothing_window", "derivative_filter_size")
JUMP_CANDIDATES = (1, 2, 5)
POSITIVE_INT_KNOBS = ("smoothing_window", "derivative_filter_size", "min_block_size",
                      "pelt_jump", "hmm_states", "min_periods")

# rt_threshold_na_handling (cell 9): the four legal values. There is NO default.
RT_THRESHOLD_NA_MODES = ("partial", "drop_stimulus", "bfill", "ffill")


def rt_threshold_na_mode(cfg: dict) -> str:
    """The configured rt_threshold_na_handling, or KnobConstraintError. None, booleans
    and any other value are refused, never coerced."""
    if "rt_threshold_na_handling" not in cfg:
        raise KnobConstraintError("rt_threshold_na_handling is missing from the config; it has "
                                  f"no default -- set one of {list(RT_THRESHOLD_NA_MODES)}.")
    mode = cfg["rt_threshold_na_handling"]
    if not (isinstance(mode, str) and mode in RT_THRESHOLD_NA_MODES):
        raise KnobConstraintError(
            f"rt_threshold_na_handling={mode!r} is not one of {list(RT_THRESHOLD_NA_MODES)}. It has "
            "no default: set it in LVL_1_CONFIG, or pass --rt_threshold_na_handling to lvl1.py.")
    return mode


def jumps_for(min_block_size: int) -> list[int]:
    """Jumps dividing min_block_size exactly, so nominal == effective min block.

    For levels that are multiples of 5 this reproduces the intended rule exactly:
    odd (25,35,45) -> {1,5}; even (20,30) -> {1,2,5}. Divisibility rather than parity,
    because parity breaks if levels change (21 is odd but 21 % 5 != 0).
    """
    if min_block_size <= 0:
        raise KnobConstraintError(f"min_block_size must be positive, got {min_block_size}")
    return [j for j in JUMP_CANDIDATES if min_block_size % j == 0]

def effective_min_block(min_block_size: int, pelt_jump: int) -> int:
    return int(math.ceil(min_block_size / pelt_jump) * pelt_jump)

def validate_config(cfg: dict, *, context: str = "config", strict: bool = True) -> None:
    problems: list[str] = []
    def fail(msg: str) -> None:
        if strict:
            raise KnobConstraintError(f"[{context}] {msg}")
        problems.append(msg)

