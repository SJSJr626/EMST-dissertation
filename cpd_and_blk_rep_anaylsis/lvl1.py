# Block ordering: order_blocks_by_inattention() (block 0 = most inattentive);
# PCA composite sign: PC1 oriented by the direction-weighted feature mean.

# Single source of truth for the display-name <-> column-name <-> direction
# contract. Every consumer of feature-display names (get_feature_column,
# detect_blocks_hmm's state ordering, create_block_methods.get_defined_on_single,
# get_validation_map, mad_center_columns, summarize_block_methods) should derive its
# mapping from this dict instead of hard-coding parallel tables. Adding a new feature
# becomes ONE entry here.
# `direction` semantics:
#   +1 = high value indicates MORE inattentive (variable, random)
#   -1 = high value indicates MORE attentive   (slow/deliberate, coherent across scales)
# NOTE on Adj RT Level (Stim): the project's operational convention is that LOW RT
# indicates inattention (rushing) -- consistent with inattent_behav's fast-RT
# threshold and the LVL_2 component selection. So Adj RT Level (Stim) has
# direction=-1 (high RT = attentive/deliberate).
# `defined_on` mirrors create_block_methods.get_defined_on_single (cell 18):
# the validation step skips features whose `defined_on` matches the method's
# own defined_on tag, so a method cannot "validate" itself.
# NAMING NOTE, so this is not "corrected" later. The three LEVEL 1 detection features
# (manuscript notation in brackets) are:
#   "Adj RT Level (Stim)" [$AdjRT_{stim}$]  stimulus-level drift-adjusted RT
#   "Adj RT Var (win)"    [$AdjVar_{win}$]  sliding-window (Esterman VTC) variance of it
#   "Entropy (win)"       [$Ent_{win}$]     sliding-window normalised response entropy
# They are NOT the Level 2 block features ("Adj RT Level (Block)", "Exp RT Var (Block)",
# "Exp Entropy (Block)"), which are rebuilt per block in the LVL_2 cells.
# The registry entry literally named "RT Variance" is the cross-scale within-stimulus
# variance; it is not used for detection or validation. All of cp_features /
# pelt_features / hmm_features use the three names above. Method IDs are derived from
# these names (spaces -> "_", parens dropped): CPD_Adj_RT_Level_Stim, HMM_2_Entropy_win.
# validation_prefix names the per-row validation columns (<prefix>_F / _p / _effsize /
# _p_holm_within): adj_rt_level_stim, adj_rt_var_win, entropy_win.
FEATURE_REGISTRY = {
    "Adj RT Level (Stim)": {"rt_col": "aggregated_rt",       "residual_col": "aggregated_residual",      "direction": -1, "defined_on": "adj_rt_level_stim",
                        "validation_prefix": "adj_rt_level_stim"},
    "RT Variance":     {"rt_col": "rt_variance",         "residual_col": "residual_variance",        "direction": +1, "defined_on": "variance",
                        "validation_prefix": "rt_var"},
    # Temporal (sliding-window) RT variance: each scale's variance over a
    # derivative_filter_size window (centred when rolling_center=True), averaged across
    # scales (temporal_var_method="per_scale") -- the Esterman variance-time-course idea.
    # Distinct from "RT Variance" (cross-scale, within-stimulus).
    "Adj RT Var (win)":    {"rt_col": "local_rt_var",        "residual_col": "local_residual_var",       "direction": +1, "defined_on": "variance",
                        "validation_prefix": "adj_rt_var_win"},
    # Coherence (RT): mean pairwise distance of RTs across scales for a given
    # stimulus (instantaneous, cross-scale). High distance = low cross-scale
    # agreement = MORE inattentive.
    "Coherence (RT)":  {"rt_col": "coherence_rt",  "residual_col": "coherence_residual",      "direction": +1, "defined_on": "coherence",
                        "validation_prefix": "coherence_rt"},
    # Coherence (Var): pairwise distance of each scale's rolling RT variance
    # (cross-scale dispersion of the local variance signal, not a single scale's
    # own variance). High distance = MORE inattentive.
    "Coherence (Var)": {"rt_col": "coherence_vars", "residual_col": "coherence_residual_vars", "direction": +1, "defined_on": "coherence",
                        "validation_prefix": "coherence_var"},
    "Entropy (win)":       {"rt_col": "rating_entropy_norm", "residual_col": "rating_entropy_norm",      "direction": +1, "defined_on": "entropy",
                        "validation_prefix": "entropy_win"},
    "Rating Variance": {"rt_col": "rating_variance",     "residual_col": "rating_variance",          "direction": +1, "defined_on": "variance",
                        "validation_prefix": "rate_var"},
}


def get_feature_column(display_name, features, config):
    """
    Map feature display name to actual column name based on use_residuals setting.

    Reads from FEATURE_REGISTRY (single source of truth, defined above).

    Parameters
    ----------
    display_name : str
        Must be a key of FEATURE_REGISTRY (e.g. "Adj RT Level (Stim)", "RT Variance",
        "Coherence (RT)", "Coherence (Var)", "Entropy (win)", "Rating Variance").
    features : pd.DataFrame
        Feature dataframe to check column availability.
    config : dict
        Config with use_residuals setting.

    Returns
    -------
    str or None
        Column name if available, None otherwise. When use_residuals=True and
        the residual column is missing, falls back to the RT column.
    """
    spec = FEATURE_REGISTRY.get(display_name)
    if spec is None:
        return None
    use_residuals = config["use_residuals"]
    primary = spec["residual_col"] if use_residuals else spec["rt_col"]
    if primary in features.columns:
        return primary
    # When the residual column is missing (e.g. the drift fit failed for this group), the RT column is used. With
    # use_residuals=False a missing RT column means something is wrong upstream, so None is returned.
    if use_residuals:
        rt_col = spec["rt_col"]
        if rt_col in features.columns:
            return rt_col
    return None


def apply_smoothing(signal, method, window):
    """
    Apply smoothing to a signal before changepoint detection.
    
    Parameters
    ----------
    signal : np.ndarray
        Input signal
    method : str
        "none", "boxcar", or "gaussian"
    window : int
        Smoothing window size
    
    Returns
    -------
    np.ndarray
        Smoothed signal
    """
    # explicit guard against invalid window sizes.
    if window <= 0:
        raise ValueError(f"smoothing_window must be > 0, got {window}")
    if method == "none" or window <= 1:
        return signal
    
    signal = np.asarray(signal, dtype=float)
    
    # NaN guard for other callers (e.g. plotting). The detectors never pass NaN: they
    # receive observed stimuli only (_on_observed_rows). np.convolve would spread a NaN
    # across the whole window, so any NaN is nearest-filled here before smoothing.
    if np.any(np.isnan(signal)):
        signal = pd.Series(signal).ffill().bfill().values
        if np.any(np.isnan(signal)):
            # All-NaN input: return as-is (cannot smooth nothing).
            return signal
    
    if method == "boxcar":
        kernel = np.ones(window) / window
    elif method == "gaussian":
        sigma = window / 6
        x = np.arange(window) - window // 2
        kernel = np.exp(-0.5 * (x / sigma) ** 2)
        kernel = kernel / kernel.sum()
    else:
        # Unknown smoothing method (typo? new value?). Warn rather than
        # silently return the unsmoothed signal -- otherwise a misspelt
        # LVL_1_CONFIG["smoothing_method"] disables smoothing without any signal.
        import warnings as _w_sm
        _w_sm.warn(
            f"apply_smoothing: unknown method '{method}'; expected one of "
            f"'none', 'boxcar', 'gaussian'. Returning signal unchanged.",
            stacklevel=2,
        )
        return signal
    
    # symmetric padding: avoids a one-element phase bias on even windows.
    pad_left = window // 2
    pad_right = (window - 1) // 2
    padded = np.pad(signal, (pad_left, pad_right), mode='reflect')
    smoothed = np.convolve(padded, kernel, mode='valid')
    
    if len(smoothed) > len(signal):
        smoothed = smoothed[:len(signal)]
    elif len(smoothed) < len(signal):
        smoothed = np.pad(smoothed, (0, len(signal) - len(smoothed)), mode='edge')
    
    return smoothed


def detect_blocks_fixed(n_trials, block_size):
    """Fixed-size blocks (ceiling division avoids orphan label)."""
    if block_size <= 0:
        raise ValueError(f"block_size must be > 0, got {block_size}")
    if n_trials <= 0:
        return np.zeros(0, dtype=int)
    n_blocks = (n_trials + block_size - 1) // block_size  # ceiling division
    return np.repeat(np.arange(n_blocks), block_size)[:n_trials]


# within-session MAD-z helper
def mad_center_columns(features):
    """Within-session robust (MAD) z-scoring of the segmentation feature columns,
    applied BEFORE MAD-CPD / HMM / PELT so every feature is on a common scale.
    Makes pelt_pen and cp_k comparable across features on different units.
    Idempotent w.r.t. the HMM / multi-feature-PELT internal MAD-z (MAD-z of MAD-z
    == MAD-z) whenever MAD > 0 (MAD = 0 only in heavily straight-lined sessions); single-feature
    PELT and the CPD threshold become scale-invariant. Returns a COPY with only the mapped feature columns
    rescaled -- the original `features` (validation / quality / block matrices) is
    untouched."""
    cols = set()
    for spec in FEATURE_REGISTRY.values():
        for key in ("rt_col", "residual_col"):
            col = spec.get(key)
            if col and col in features.columns:
                cols.add(col)
    if not cols:
        return features
    out = features.copy()
    for col in cols:
        out[col] = robust_scale(out[col].to_numpy(dtype=float), zero_mad="floor")
    return out


# EM stopping rule for detect_blocks_hmm. hmmlearn's stock ConvergenceMonitor stops
# when the SIGNED change in log-likelihood is < tol, so ANY decrease ends EM. With the
# transition prior the M-step maximises log-likelihood + log-prior; the plain
# log-likelihood can dip while that objective is still rising, and the stock rule
# stopped those fits at the dip. This monitor stops on the ABSOLUTE change instead.
# Installed the way hmmlearn documents it: point model.monitor_ at a subclass
# before fit().
from hmmlearn.base import ConvergenceMonitor as _HMMConvergenceMonitor


class AbsDeltaConvergenceMonitor(_HMMConvergenceMonitor):
    """Converged when |loglik_t - loglik_(t-1)| < tol, or when n_iter is reached."""
    @property
    def converged(self):
        return (self.iter == self.n_iter or
                (len(self.history) >= 2 and
                 abs(self.history[-1] - self.history[-2]) < self.tol))


# HMM transmat prior + per-feature smoothing
def detect_blocks_hmm(features, n_states, feature_list, config, participant_id=None, session_id=None):
    """
    Generic HMM block detection using configurable feature list.
    
    Parameters
    ----------
    features : pd.DataFrame
        Feature dataframe
    n_states : int
        Number of HMM states
    feature_list : list
        List of feature display names (e.g., ["Adj RT Level (Stim)", "Adj RT Var (win)"])
    config : dict
        Configuration with HMM settings
        
    Returns
    -------
    np.ndarray
        Block assignments
    """
    n_iter = config["hmm_n_iter"]
    tol = float(config["hmm_tol"])
    random_state = config["hmm_random_state"]
    cov_type = config["hmm_covariance_type"]
    
    # Map display names to column names. keep parallel
    # display-name list so the post-fit state-ordering can apply
    # direction-aware MAD-z scoring instead of summing raw means.
    cols = []
    display_for_col = []
    for name in feature_list:
        col = get_feature_column(name, features, config)
        if col:
            cols.append(col)
            display_for_col.append(name)
    
    if len(cols) < 1:
        return np.zeros(len(features), dtype=int)
    
    # Prepare feature matrix. No fill: every detector receives only stimuli whose
    # features are all observed (_on_observed_rows, cell 18); rolling-window edges and
    # NaN stimuli (e.g. rt_threshold_na_handling="drop_stimulus") are removed before this
    # call and inherit a block after.
    X = features[cols].to_numpy(dtype=float)

    # Robust z per column (shared helper; MAD = 0 -> eps floor).
    X = robust_scale(X, zero_mad="floor")

    # Smooth each feature column before fitting, with the same smoothing_method /
    # smoothing_window as detect_blocks_cpd and detect_blocks_pelt ('none' = no-op).
    _sm_method = config["smoothing_method"]
    _sm_window = config["smoothing_window"]
    X = X.astype(float)
    for _j in range(X.shape[1]):
        X[:, _j] = apply_smoothing(X[:, _j], _sm_method, _sm_window)

    # state-persistence prior on the transition matrix. We want the
    # EFFECTIVE pseudo-counts hmmlearn adds to be exactly `hmm_transmat_self_prior`
    # on the diagonal and ZERO off-diagonal. hmmlearn's MAP step computes
    # (transmat_prior - 1 + observed_counts), so we pass (self + 1) on the diagonal
    # and 1 off-diagonal: the -1 cancels everywhere -> off-diagonals add nothing
    # (pure observed counts, no suppression of lone switches) and each diagonal
    # adds exactly `self` pseudo self-transitions. It is a pseudo-COUNT, not a
    # percentage; its strength is relative to the ~T-1 observed transitions per
    # session. Higher self = stickier states = fewer, longer blocks. 0 -> no
    # prior (matches hmmlearn's transmat_prior=1.0 default = pure ML EM).
    _self_p = float(config["hmm_transmat_self_prior"])
    _transmat_prior = np.ones((n_states, n_states), dtype=float)   # off-diag 1 -> effective 0
    np.fill_diagonal(_transmat_prior, _self_p + 1.0)               # diag -> effective +_self_p

    # Set inside the function on purpose: block detection runs under joblib/loky, and
    # child processes do not inherit the parent's logging configuration.
    logging.getLogger("hmmlearn").setLevel(logging.CRITICAL)

    try:
        model = hmm.GaussianHMM(n_components=n_states, covariance_type=cov_type,
                                n_iter=n_iter, tol=tol, random_state=random_state,
                                transmat_prior=_transmat_prior, verbose=False)
        model.monitor_ = AbsDeltaConvergenceMonitor(tol, n_iter, False)
        model.fit(X)
        # hmmlearn's monitor_.converged is True whenever iter == n_iter, so it reports
        # success for a fit that merely exhausted its iteration budget. Decide from the
        # log-likelihood history instead: hitting the cap, or a final decrease larger
        # than tol. Changes within +/-tol are what the stopping rule itself treats as
        # converged, so they are not flagged.
        _mon = getattr(model, "monitor_", None)
        _hist = list(getattr(_mon, "history", []) or [])
        _delta = (_hist[-1] - _hist[-2]) if len(_hist) >= 2 else None
        _hit_cap = bool(_mon is not None and _mon.iter >= n_iter)
        _decreased = bool(_delta is not None and _delta < -tol)
        if _hit_cap or _decreased:
            _why = "hit_iter_cap" if _hit_cap else "loglik_decreased"
            print(f"[HMM non-convergence] id={participant_id} session={session_id} "
                  f"n_states={n_states} n_iter={n_iter} reason={_why} "
                  f"delta={_delta if _delta is not None else float('nan'):+.4g}")
        states = model.predict(X)
        
        # Order states by composite score (higher = more inattentive).
        # Direction-aware MAD-z scoring:
        # Raw summed means are dominated by RT-Level scale; MAD-normalized
        # contributions with explicit signs respect the theoretical direction
        # of each feature (high coherence = MORE attentive, etc.).
        # NOTE: state ordering is QC/diagnostic only — block boundaries
        # drive downstream analysis, ordering does not.
        # Direction sign per feature -- single source of truth lives in
        # FEATURE_REGISTRY. The feature is spelled "Coherence (Var)".
        _state_directions = {name: spec["direction"] for name, spec in FEATURE_REGISTRY.items()}
        _col_meds, _col_mads = robust_center_scale(features[cols], zero_mad="floor")
        state_scores = []
        for s in range(n_states):
            mask = states == s
            if mask.sum() > 0:
                score = 0.0
                for _col, _disp in zip(cols, display_for_col):
                    _dir = _state_directions.get(_disp, +1)  # unknown features default to +1
                    _z = (features.loc[mask, _col].mean() - _col_meds[_col]) / _col_mads[_col]
                    score += _dir * float(_z)
            else:
                score = 0.0
            state_scores.append(score)
        
        # Higher score = more inattentive (State 0)
        order = np.argsort(state_scores)[::-1]
        state_map = {old: new for new, old in enumerate(order)}
        ordered_states = np.array([state_map[s] for s in states])
        # Log HMM diagnostic (block count = number of runs in state sequence).
        n_runs = 1 + int(np.sum(np.diff(ordered_states) != 0)) if len(ordered_states) > 0 else 0
        _CPD_DIAGNOSTICS.append({
            "participant": participant_id,
            "session": session_id,
            "method": f"HMM_{n_states}",
            "n_trials": len(features),
            "mad": np.nan,
            "median_diff": np.nan,
            "mad_window_size": None,
            "k_used": np.nan,
            "n_changepoints": max(0, n_runs - 1),
            "n_blocks": n_runs,
            "features_used": ",".join(feature_list),
            "hmm_converged": not (_hit_cap or _decreased),
        })
        return ordered_states
    except Exception as _e_hmm:
        # A failed fit returns one block (all zeros); it is recorded as a failure in the diagnostics and, through
        # process_session, in the results (detector_failed), so it is not read as a genuine one-block segmentation.
        import warnings as _w_c3
        _w_c3.warn(
            f"detect_blocks_hmm: HMM failed for id={participant_id} session={session_id} "
            f"(n_states={n_states}, features={feature_list}) ({type(_e_hmm).__name__}: {_e_hmm}); "
            f"returning one block, recorded as detector_failed",
            stacklevel=2,
        )
        _CPD_DIAGNOSTICS.append({
            "participant": participant_id, "session": session_id, "method": f"HMM_{n_states}",
            "n_trials": len(features), "n_blocks": 1, "features_used": ",".join(feature_list),
            "detector_failed": True,
        })
        return np.zeros(len(features), dtype=int)

_CPD_DIAGNOSTICS = []


def get_cpd_diagnostics_df():
    """Return accumulated CPD diagnostics as a DataFrame (one row per call)."""
    return pd.DataFrame(_CPD_DIAGNOSTICS) if _CPD_DIAGNOSTICS else pd.DataFrame()



def _compute_diff_thresholds(diffs, k, mad_window_size, min_periods=None, center=True):
    """
    Compute per-gap (threshold, median_diff, mad) for changepoint detection.

    Parameters
    ----------
    diffs : np.ndarray
        Absolute first-differences of the signal, length n-1.
    k : float
        Sensitivity multiplier.
    mad_window_size : int or None
        None -> global scalar MAD over all diffs.
        int  -> centered sliding window of that many stimuli around each gap.

    Returns
    -------
    threshold : np.ndarray (length n-1)
    median_diff_summary : float (scalar; for windowed path returns median of local medians)
    mad_summary : float (scalar; for windowed path returns median of local MADs)
    """
    if mad_window_size is None or int(mad_window_size) >= len(diffs):
        med = float(np.median(diffs))
        m = float(mad(diffs))
        local_med = np.full_like(diffs, med, dtype=float)
        local_mad = np.full_like(diffs, m, dtype=float)
        thr = local_med + k * local_mad * MAD_TO_SD
        return thr, local_med, local_mad
    # pandas rolling with center=rolling_center and min_periods, like the rolling
    # features. These are THRESHOLDS, not feature values: undefined edge thresholds
    # take the nearest defined threshold.
    w = int(mad_window_size)
    s = pd.Series(diffs, dtype=float)
    roll = s.rolling(w, center=center, min_periods=min_periods)
    local_med = roll.median()
    local_mad = roll.apply(mad, raw=True)
    local_med = local_med.bfill().ffill().to_numpy()
    local_mad = local_mad.bfill().ffill().to_numpy()
    thr = local_med + k * local_mad * MAD_TO_SD
    return thr, local_med, local_mad


# ======================================================================================
# Direction-aware block ordering, shared by detect_blocks_cpd and detect_blocks_pelt.
# Convention: BLOCK 0 = MOST INATTENTIVE, matching the state ordering of detect_blocks_hmm
# (a direction-weighted MAD-z composite). Ordering by the raw signal mean instead would
# reverse this on a direction = -1 feature (e.g. "Adj RT Level (Stim)", where SLOW =
# attentive), so block 0 would mean different things for different detectors.
# Sign comes from FEATURE_REGISTRY[...]["direction"].
# ======================================================================================
def order_blocks_by_inattention(blocks, features, cols, display_names):
    """Renumber blocks so that block 0 is the most inattentive.

    Parameters
    ----------
    blocks : np.ndarray
        Integer block assignment per trial.
    features : pd.DataFrame
        Feature frame the blocks were detected on.
    cols : list[str]
        Concrete column names used for detection.
    display_names : list[str]
        FEATURE_REGISTRY display names, parallel to `cols`.

    Returns
    -------
    np.ndarray
        Renumbered block assignments.
    """
    unique_blocks = np.unique(blocks)
    if len(unique_blocks) <= 1:
        return blocks

    directions = {name: spec["direction"] for name, spec in FEATURE_REGISTRY.items()}
    col_meds, col_mads = robust_center_scale(features[cols], zero_mad="floor")

    scores = []
    for b in unique_blocks:
        mask = blocks == b
        if mask.sum() == 0:
            scores.append(0.0)
            continue
        score = 0.0
        for col, disp in zip(cols, display_names):
            direction = directions.get(disp, +1)   # unknown features default to +1
            z = (features.loc[mask, col].mean() - col_meds[col]) / col_mads[col]
            score += direction * float(z)
        scores.append(score)

    # Higher composite score = more inattentive = block 0.
    order = np.argsort(scores)[::-1]
    block_map = {int(unique_blocks[old]): new for new, old in enumerate(order)}
    return np.array([block_map[int(b)] for b in blocks])


def detect_blocks_cpd(features, feature_list, config, composite_method="average",
                      participant_id=None, session_id=None):
    """
    Unified changepoint detection using configurable feature list.
    
    Stores MAD diagnostics in _CPD_DIAGNOSTICS for later reporting.
    
    Parameters
    ----------
    features : pd.DataFrame
        Feature dataframe
    feature_list : list
        List of feature display names
    config : dict
        Configuration with CP settings
    composite_method : str
        "average" or "PCA" for combining multiple features
    participant_id : str or int, optional
        Participant identifier for diagnostic logging
    session_id : str or int, optional
        Session identifier for diagnostic logging
        
    Returns
    -------
    np.ndarray
        Block assignments
    """
    global _CPD_DIAGNOSTICS 

    min_block = config["min_block_size"]
    smoothing_method = config["smoothing_method"]
    smoothing_window = config["smoothing_window"]
    
    n = len(features)
    
    # Map display names to column names
    cols = []
    display_for_col_cpd = []   # parallel display names, needed for direction lookup
    for name in feature_list:
        col = get_feature_column(name, features, config)
        if col:
            cols.append(col)
            display_for_col_cpd.append(name)

    if len(cols) == 0:
        return np.zeros(n, dtype=int)
    
    # Combine features into signal
    # No fill anywhere below: detectors receive observed stimuli only (cell 18).
    _pca_stats = None
    if len(cols) == 1:
        signal = features[cols[0]].to_numpy(dtype=float)
    else:
        if composite_method == "PCA":
            from sklearn.decomposition import PCA
            X = features[cols].copy()
            # Robust z per column; a MAD <= 1e-6 is replaced by the column SD.
            X = robust_scale(X, zero_mad="sd", sd_below=1e-6)
            # Fit PCA with all components so we get eigenvalues + variance ratios.
            n_comp_full = min(len(cols), max(1, X.shape[0] - 1))
            pca_full = PCA(n_components=n_comp_full).fit(X.values)
            _pca_eigs = pca_full.explained_variance_
            _pca_evar = pca_full.explained_variance_ratio_
            signal = pca_full.transform(X.values)[:, 0]
            # scikit-learn does not fix PC1's sign across fits,
            # so the composite signal (and therefore block ordering) could flip between
            # participants. Orient PC1 against the direction-weighted mean of the
            # standardised features so the sign is deterministic and comparable.
            _dirs = {name: spec["direction"] for name, spec in FEATURE_REGISTRY.items()}
            _oriented = np.nanmean(
                np.vstack([
                    _dirs.get(_disp, +1) * X.values[:, _j]
                    for _j, _disp in enumerate(display_for_col_cpd)
                ]),
                axis=0,
            )
            if np.dot(signal, _oriented) < 0:
                signal = -signal
            # Bartlett sphericity (manual): chi2 = -[n-1-(2p+5)/6] * ln(det(R))
            try:
                _corr = np.corrcoef(X.values, rowvar=False)
                _det = float(np.linalg.det(_corr))
                _n_obs, _p_vars = X.shape
                if _det > 0 and _n_obs > 5:
                    from scipy.stats import chi2 as _chi2
                    _bart_chi2 = -((_n_obs - 1.0 - (2.0 * _p_vars + 5.0) / 6.0)) * np.log(_det)
                    _bart_df = _p_vars * (_p_vars - 1) // 2
                    _bart_p = float(1.0 - _chi2.cdf(_bart_chi2, df=_bart_df))
                else:
                    _bart_chi2 = float("inf")
                    _bart_p = 0.0
            except Exception:
                _bart_chi2 = float("nan")
                _bart_p = float("nan")
            _pca_stats = {
                "pca_explained_var_ratio_pc1": float(_pca_evar[0]) if len(_pca_evar) else float("nan"),
                "pca_eigenvalue_pc1": float(_pca_eigs[0]) if len(_pca_eigs) else float("nan"),
                "pca_eigenvalues": tuple(float(e) for e in _pca_eigs),
                "pca_bartlett_chi2": float(_bart_chi2),
                "pca_bartlett_p": float(_bart_p),
                "pca_n_components": int(_n_comp_full := n_comp_full),
            }
        else:
            components = []
            for col in cols:
                comp = features[col].values.copy()
                if np.all(np.isnan(comp)):
                    import warnings as _w_m6
                    _w_m6.warn(
                        f"detect_blocks_cpd: feature '{col}' is all-NaN; excluded",
                        stacklevel=2,
                    )
                    continue
                comp = (comp - np.nanmean(comp)) / (np.nanstd(comp) + 1e-8)
                components.append(comp)
            if not components:
                return np.zeros(n, dtype=int)
            signal = np.nanmean(np.vstack(components), axis=0)
    
    signal = apply_smoothing(signal, smoothing_method, smoothing_window)
    
    k = float(config["cp_k"])
    mad_window_size = config["mad_window_size"]
    diffs = np.abs(np.diff(signal))
    threshold, local_med_arr, local_mad_arr = _compute_diff_thresholds(
        diffs, k, mad_window_size,
        min_periods=config["min_periods"], center=config["rolling_center"])
    diff_scores = robust_z(diffs, local_med_arr, local_mad_arr)
    median_diff = float(np.median(local_med_arr))
    mad = float(np.median(local_mad_arr))
    
    changepoints = np.where(diffs > threshold)[0] + 1
    
    if len(changepoints) > 0:
        filtered = [changepoints[0]] if changepoints[0] >= min_block else []
        last_cp = filtered[-1] if filtered else 0
        for cp in changepoints[1:]:
            if cp - last_cp >= min_block:
                filtered.append(cp)
                last_cp = cp
        if filtered and (n - filtered[-1] < min_block):
            filtered.pop()
        changepoints = np.array(filtered) if filtered else np.array([])
    else:
        changepoints = np.array([])
    
    # === STORE DIAGNOSTIC ===
    _CPD_DIAGNOSTICS.append({
        "participant": participant_id,
        "session": session_id,
        "method": "CPD",
        "n_trials": n,
        "mad": mad,
        "median_diff": median_diff,
        "mad_window_size": mad_window_size,
        "k_used": k,
        "n_changepoints": len(changepoints),
        "n_blocks": len(changepoints) + 1,
        "features_used": ",".join(feature_list),
        "diffs": diffs.copy(),
        "local_med": local_med_arr.copy(),
        "local_mad": local_mad_arr.copy(),
        "diff_scores": diff_scores.copy(),
    })
    if _pca_stats is not None:
        _CPD_DIAGNOSTICS[-1].update(_pca_stats)

    # Create block labels + reorder
    blocks = np.zeros(n, dtype=int)
    for i, cp in enumerate(changepoints):
        blocks[cp:] = i + 1
    
    # direction-aware ordering; block 0 = most inattentive.
    blocks = order_blocks_by_inattention(blocks, features, cols, display_for_col_cpd)

    return blocks


# dimension-aware PELT penalty (uni/multi)
def detect_blocks_pelt(features, feature_list, config, composite_method="average",
                       participant_id=None, session_id=None):
    """
    PELT changepoint detection via the `ruptures` library.

    Penalty-based segmentation: no manual k. Tune `pelt_pen_uni` / `pelt_pen_multi` (higher =
    fewer breakpoints). Builds the same signal as `detect_blocks_cpd`, then
    delegates segmentation to `ruptures.Pelt`.

    Diagnostic record uses the same _CPD_DIAGNOSTICS list as MAD-CPD so the
    report can show PELT alongside the other families.
    """
    global _CPD_DIAGNOSTICS

    min_block = config["min_block_size"]
    pelt_model = config["pelt_model"]
    _pen_uni = float(config["pelt_pen_uni"])
    _pen_multi = float(config["pelt_pen_multi"])
    pelt_jump = int(config["pelt_jump"])
    smoothing_method = config["smoothing_method"]
    smoothing_window = config["smoothing_window"]

    n = len(features)

    cols = []
    display_for_col = []   # parallel display names, needed for direction lookup
    for name in feature_list:
        col = get_feature_column(name, features, config)
        if col:
            cols.append(col)
            display_for_col.append(name)
    if len(cols) == 0:
        return np.zeros(n, dtype=int)

    # Build signal. Single feature -> 1D (mirrors detect_blocks_cpd). Multi-feature
    # -> 2D (n_trials, n_features) so PELT operates in the joint space rather than
    # on a 1D projection. MAD-z normalize per column so cost-function scale matches.
    # No fill: detectors receive observed stimuli only (cell 18).
    if len(cols) == 1:
        signal = features[cols[0]].to_numpy(dtype=float)
        signal = apply_smoothing(signal, smoothing_method, smoothing_window)
        fit_data = signal.reshape(-1, 1)
        block_ordering_signal = signal
    else:
        X = features[cols].copy()
        X = robust_scale(X, zero_mad="floor")
        # Smooth each column independently before fitting.
        Xv = X.values.astype(float)
        for j in range(Xv.shape[1]):
            Xv[:, j] = apply_smoothing(Xv[:, j], smoothing_method, smoothing_window)
        fit_data = Xv
        # For final block-label ordering, use the average across z-scored columns.
        block_ordering_signal = np.nanmean(Xv, axis=1)

    # Dimension-aware penalty: multivariate PELT cost sums over features, so it
    # needs a larger penalty than univariate (BIC ~ dim*log(n)). Separate knobs.
    pelt_pen = _pen_uni if fit_data.shape[1] == 1 else _pen_multi

    try:
        algo = rpt.Pelt(model=pelt_model, jump=pelt_jump, min_size=int(min_block)).fit(fit_data)
        bkps = algo.predict(pen=pelt_pen)
        changepoints = np.array([b for b in bkps[:-1] if 0 < b < n], dtype=int)
    except Exception as e:
        import warnings as _w
        _w.warn(f"detect_blocks_pelt failed: {type(e).__name__}: {e}", stacklevel=2)
        return np.zeros(n, dtype=int)

    # k_used is a CROSS-METHOD COLUMN. Different detectors store different
    # "tuning parameter" values in this slot so a single diagnostics DataFrame
    # can be sorted/filtered across families:
    #   * MAD-CPD              -> stores k  (the MAD multiplier)
    #   * HMM                  -> NaN (HMM has no scalar sensitivity knob)
    #   * PELT                 -> stores pelt_pen (penalty; higher = fewer cps)
    # Readers comparing rows across detectors should remember the unit of
    # k_used depends on the row's `method` column, not on a shared scale.
    _CPD_DIAGNOSTICS.append({
        "participant": participant_id,
        "session": session_id,
        "method": "PELT",
        "n_trials": n,
        "mad": np.nan,
        "median_diff": np.nan,
        "mad_window_size": None,
        "k_used": pelt_pen,        # see note above re: cross-method overload
        "n_changepoints": len(changepoints),
        "n_blocks": len(changepoints) + 1,
        "features_used": ",".join(feature_list),
        "pelt_model": pelt_model,
        "pelt_n_features": int(fit_data.shape[1]),
    })

    blocks = np.zeros(n, dtype=int)
    for i, cp in enumerate(changepoints):
        blocks[cp:] = i + 1

    unique_blocks = np.unique(blocks)
    if len(unique_blocks) > 1:
        # direction-aware ordering; block 0 = most inattentive.
        blocks = order_blocks_by_inattention(blocks, features, cols, display_for_col)

    return blocks

