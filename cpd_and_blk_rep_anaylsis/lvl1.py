def fill_rejected(values, rejected, direction, groups=None):
    """Replace ONLY the `rejected` cells of `values` by the next ("bfill") or previous
    ("ffill") non-missing value, within `groups` (e.g. id and session) when given.

    The single implementation of the rt_threshold_na_handling fills (cell 19). Every
    cell that is not rejected is returned unchanged, whatever it holds -- a rolling-
    window edge, a naturally missing value or a valid value. Rejected cells are emptied
    before the fill, so they are never a source for each other; a rejected cell with no
    valid value in `direction` stays NaN (there is no switch to the other direction)."""
    if direction not in ("bfill", "ffill"):
        raise ValueError(f"fill_rejected: direction must be 'bfill' or 'ffill', got {direction!r}")
    out = pd.Series(values, dtype=float, copy=True)
    rej = np.asarray(rejected, dtype=bool)
    if not rej.any():
        return out
    out[rej] = np.nan
    src = out.groupby(groups, sort=False) if groups is not None else out
    src = src.bfill() if direction == "bfill" else src.ffill()
    out[rej] = src[rej]
    return out


def compute_stim_resp_features(stim_lvl_df, config, rt_rejected=None, rt_rejected_fill=None):
    """
    Extract comprehensive features for each stimulus (one row per stim_order).

    Parameters
    ----------
    stim_lvl_df : pd.DataFrame
        Stim-level data with {scale}_rt, {scale}_response columns (and optional id/session/stim_order)
    config : dict
        Configuration dictionary (required)
    rt_rejected : pd.DataFrame of bool, optional
        One column per scale, same index as stim_lvl_df: True where that scale's rating
        was rejected by min_rt_thresh / max_rt_thresh (cell 19, level1_features). The
        caller has already removed or filled those {scale}_rt / {scale}_residual values.
        Here the rejected slot is left out of that scale's rolling-variance windows.
        None = no rejected cells.
    rt_rejected_fill : None | "bfill" | "ffill"
        None ("partial"): that scale's variance AT a rejected stimulus is NaN.
        "bfill"/"ffill": that scale's variance at a rejected stimulus is its own window's
        variance of the remaining valid values. Only when that window has fewer than
        min_periods of them is it filled from the next / previous valid variance of the
        same scale in the same session (fill_rejected) -- and not in a rolling-window
        edge, which stays NaN like every edge.

    Returns
    -------
    pd.DataFrame
        Stim-level data with computed features.
        
    Feature Notes
    -------------
    Detection / validation features (FEATURE_REGISTRY):
        - aggregated_residual (aggregated_rt when use_residuals=False): Adj RT Level (Stim),
          the rt_aggregation (mean) of the per-scale values
        - local_residual_var (local_rt_var): Adj RT Var (win), rolling per-scale variance
          averaged across scales (temporal_var_method="per_scale")
        - rating_entropy_norm: Entropy (win), rolling per-scale Shannon entropy / ln(K),
          averaged across scales. Low = straightlining, high = random responding.
    Rolling windows: derivative_filter_size wide, rolling_center, min_periods non-missing
    values; windows below min_periods are NaN and are not filled.
    Also computed but not used for detection or validation: cross-scale variances,
    coherence features, local means, per-scale entropies, index columns.
    """
    df = stim_lvl_df.copy()

    # Rejected-RT flags ride through the sort as temporary columns (removed below).
    _REJ = "__rt_rejected__"
    if rt_rejected is not None:
        if rt_rejected_fill not in (None, "bfill", "ffill"):
            raise ValueError(f"rt_rejected_fill must be None, 'bfill' or 'ffill', got {rt_rejected_fill!r}")
        for _s in config["scale_ranges"]:
            df[f"{_REJ}{_s}"] = rt_rejected[_s].reindex(df.index, fill_value=False).to_numpy(dtype=bool)

    # Robust ordering: always sort before rolling/gradient features
    sort_cols = [c for c in ["id", "session", "stim_order"] if c in df.columns]
    if sort_cols:
        df = df.sort_values(sort_cols).reset_index(drop=True)
    rej_by_scale = ({_s: df.pop(f"{_REJ}{_s}").to_numpy(dtype=bool) for _s in config["scale_ranges"]}
                    if rt_rejected is not None else {})
    _sess_keys = [c for c in ["id", "session"] if c in df.columns]

    def scale_rolling_var(series, scale):
        """Rolling variance of one scale's series. A rejected slot never enters a window.
        At a rejected stimulus: "partial" -> NaN; "bfill"/"ffill" -> the window's variance
        of the remaining valid values, filled from the neighbouring valid variance only
        where that window is below min_periods but would reach it with the rejected
        slots counted as observed. A rejected stimulus in a rolling-window edge (or an
        otherwise under-filled window) keeps that NaN: the knob never fills an edge."""
        rej = rej_by_scale.get(scale)
        if rej is None or not rej.any():
            return series.rolling(window, center=center, min_periods=min_periods).var().values
        v = series.mask(rej).rolling(window, center=center, min_periods=min_periods).var()
        if rt_rejected_fill is None:
            v[rej] = np.nan
        else:
            n_obs = (series.notna().to_numpy() | rej).astype(float)
            n_obs = pd.Series(n_obs).rolling(window, center=center, min_periods=1).sum().to_numpy()
            short = rej & v.isna().to_numpy() & (n_obs >= min_periods)
            v = fill_rejected(v, short, rt_rejected_fill,
                              groups=[df[c].to_numpy() for c in _sess_keys] or None)
        return v.values

    window = config["derivative_filter_size"]
    min_periods = config["min_periods"]
    scales = list(config["scale_ranges"].keys())
    center = config["rolling_center"]

    n = len(df)

    # Identify available columns
    rt_cols = [f"{s}_rt" for s in scales if f"{s}_rt" in df.columns]
    resp_cols = [f"{s}_response" for s in scales if f"{s}_response" in df.columns]
    resid_cols = [f"{s}_residual" for s in scales if f"{s}_residual" in df.columns]

    if not rt_cols:
        raise ValueError("No RT columns found!")

    rt_matrix = df[rt_cols].to_numpy(dtype=float)

    # === HELPER: Pairwise Distance Sum ===
    def pairwise_distance_mean(row):
        valid = row[~np.isnan(row)]
        if len(valid) < 2:
            return np.nan
        total = 0.0
        n_pairs = 0
        for i in range(len(valid)):
            for j in range(i + 1, len(valid)):
                total += abs(valid[i] - valid[j])
                n_pairs += 1
        return total / n_pairs  # normalize by number of pairs

    # === HELPER: Shannon Entropy ===
    def shannon_entropy(values):
        """
        Compute Shannon entropy of a discrete distribution.
        H = -Σ p(x) * log(p(x))
        
        Returns entropy in nats (natural log). 
        Returns NaN if not enough valid values.
        """
        valid = values[~np.isnan(values)]
        if len(valid) < 2:
            return np.nan
        
        # round-then-validate instead of silent astype(int) truncation.
        # Truncating 1.5 → 1 distorts entropy on data-entry-error rows that
        # passed the in-range check but contain non-integer responses.
        rounded = np.round(valid).astype(int)
        if not np.allclose(rounded, valid, atol=1e-6):
            import warnings as _w_se
            _w_se.warn(
                "shannon_entropy: non-integer responses detected; rounded for entropy calc",
                stacklevel=2,
            )
        # Count frequency of each unique value
        unique, counts = np.unique(rounded, return_counts=True)
        probs = counts / counts.sum()
        
        # Shannon entropy: -Σ p * log(p)
        # Only include non-zero probabilities
        entropy = -np.sum(probs * np.log(probs))
        return entropy

    # =========================================================================
    # RT-BASED FEATURES (for use_residuals=False)
    # =========================================================================
    # Aggregation method from config (median when no config is passed)
    rt_agg = config["rt_aggregation"] if config else "median"
    
    df["mean_rt"] = np.nanmean(rt_matrix, axis=1)
    df["median_rt"] = np.nanmedian(rt_matrix, axis=1)
    
    # Set aggregated_rt based on rt_aggregation config
    if rt_agg == "mean":
        df["aggregated_rt"] = df["mean_rt"]
    else:
        df["aggregated_rt"] = df["median_rt"]
    df["rt_variance"] = np.nanvar(rt_matrix, axis=1)
    df["rt_std"] = np.nanstd(rt_matrix, axis=1)
    
    # Rating variance: variance of responses across scales for each stimulus.
    # Measures how much a participant differentiates between scales for each
    # stimulus. Restrict to ordinal/continuous scales -- nominal codes (e.g.,
    # emotion 1-7) are not numerically meaningful, so including them in
    # arithmetic variance contaminates the feature.
    if resp_cols:
        _scale_types_cfg = config["scale_types"]
        _ordinal_resp_cols = [
            c for c in resp_cols
            if _scale_types_cfg[c.replace("_response", "")] != "nominal"
        ]
        if _ordinal_resp_cols:
            resp_matrix = df[_ordinal_resp_cols].to_numpy(dtype=float)
            df["rating_variance"] = np.nanvar(resp_matrix, axis=1)
        else:
            # All response scales are nominal -- no meaningful rating_variance.
            df["rating_variance"] = np.nan

    # Local statistics (use aggregated_rt)
    rt_series = pd.Series(df["aggregated_rt"].values)
    df["local_rt_mean"] = rt_series.rolling(window, center=center, min_periods=min_periods).mean()
    # Sliding temporal RT var. Windows with < min_periods valid values stay NaN (never
    # filled); detectors run on observed rows only and the NaN stimuli inherit the
    # neighbouring block (cell 18). Same rule as Entropy (win) below.
    df["local_rt_var"] = rt_series.rolling(window, center=center, min_periods=min_periods).var()
    # Whole-task (GLOBAL) RT variance: variance of aggregated_rt over the ENTIRE session,
    # broadcast to every stimulus (constant within id x session). A person-level RT-
    # variability trait exposed for the BLOCK/CLUSTER stage ONLY -- constant over time,
    # so it CANNOT produce changepoints (never put it in cp_/pelt_/hmm_features).
    _gvcols = [c for c in ["id", "session"] if c in df.columns]
    # whole-task global RT var
    df["global_rt_var"] = (df.groupby(_gvcols)["aggregated_rt"].transform("var")
                           if _gvcols else df["aggregated_rt"].var())

    # Coherence (RT): pairwise distance of instantaneous RTs
    df["coherence_rt"] = np.apply_along_axis(pairwise_distance_mean, 1, rt_matrix)
    df["local_coherence_rt"] = pd.Series(df["coherence_rt"]).rolling(
        window, center=center, min_periods=min_periods
    ).mean()

    # Coherence (Var): pairwise distance of rolling variances per scale
    per_scale_rt_vars = {}
    for col in rt_cols:
        scale_name = col.replace("_rt", "")
        per_scale_rt_vars[scale_name] = scale_rolling_var(pd.Series(df[col]), scale_name)

    rt_var_matrix = np.column_stack([per_scale_rt_vars[s] for s in scales if f"{s}_rt" in df.columns])
    df["coherence_vars"] = np.apply_along_axis(pairwise_distance_mean, 1, rt_var_matrix)

    # "Adj RT Var (win)" temporal-variance flavour (config temporal_var_method). Default
    # "aggregate" (local_rt_var set above from aggregated_rt). "per_scale" instead
    # averages each scale's own rolling temporal variance (rt_var_matrix, already
    # computed for coherence_vars) -> mean-per-scale VTC. Edge / under-filled windows
    # stay NaN, exactly as for Entropy (win).
    if config["temporal_var_method"] == "per_scale":
        # temporal_var_method=per_scale override
        df["local_rt_var"] = pd.Series(np.nanmean(rt_var_matrix, axis=1))
    df["local_coherence_vars"] = pd.Series(df["coherence_vars"]).rolling(
        window, center=center, min_periods=min_periods
    ).mean()

    # =========================================================================
    # RESIDUAL-BASED FEATURES (for use_residuals=True)
    # =========================================================================
    if resid_cols:
        resid_matrix = df[resid_cols].to_numpy(dtype=float)
        
        # Level: aggregated residual across scales (mean or median based on config)
        df["mean_residual"] = np.nanmean(resid_matrix, axis=1)
        df["median_residual_raw"] = np.nanmedian(resid_matrix, axis=1)

        # NOTE -- naming quirk: `median_residual` holds whichever aggregation
        # rt_aggregation selected (mean OR median), NOT necessarily a median.
        # The name is kept because downstream consumers (get_validation_map /
        # get_feature_column) read it.
        # If rt_aggregation=="mean", median_residual == mean_residual.
        if rt_agg == "mean":
            df["median_residual"] = df["mean_residual"]
        else:
            df["median_residual"] = df["median_residual_raw"]
        
        # aggregated_residual mirrors aggregated_rt: uses rt_aggregation to match naming expected
        # by get_validation_map and get_feature_column
        df["aggregated_residual"] = df["median_residual"]
        
        # Variance: variance of residuals across scales
        df["residual_variance"] = np.nanvar(resid_matrix, axis=1)
        
        # Local statistics (use median_residual)
        resid_series = pd.Series(df["median_residual"].values)
        df["local_residual_mean"] = resid_series.rolling(window, center=center, min_periods=min_periods).mean()
        df["local_residual_var"] = resid_series.rolling(window, center=center, min_periods=min_periods).var()
        # residual counterpart of global_rt_var (whole-task variance; block/cluster only).
        _gvcols_r = [c for c in ["id", "session"] if c in df.columns]
        df["global_residual_var"] = (df.groupby(_gvcols_r)["median_residual"].transform("var")
                                     if _gvcols_r else df["median_residual"].var())
        
        # Coherence (Residual): pairwise distance of instantaneous residuals
        df["coherence_residual"] = np.apply_along_axis(pairwise_distance_mean, 1, resid_matrix)
        df["local_coherence_residual"] = pd.Series(df["coherence_residual"]).rolling(
            window, center=center, min_periods=min_periods
        ).mean()
        
        # Coherence (Residual Vars): pairwise distance of rolling residual variances per scale
        per_scale_resid_vars = {}
        for col in resid_cols:
            scale_name = col.replace("_residual", "")
            per_scale_resid_vars[scale_name] = scale_rolling_var(pd.Series(df[col]), scale_name)
        
        resid_var_matrix = np.column_stack([per_scale_resid_vars[s] for s in scales if f"{s}_residual" in df.columns])
        df["coherence_residual_vars"] = np.apply_along_axis(pairwise_distance_mean, 1, resid_var_matrix)

        # residual counterpart of the temporal_var_method toggle (see RT side).
        if config["temporal_var_method"] == "per_scale":
            df["local_residual_var"] = pd.Series(np.nanmean(resid_var_matrix, axis=1))
        df["local_coherence_residual_vars"] = pd.Series(df["coherence_residual_vars"]).rolling(
            window, center=center, min_periods=min_periods
        ).mean()

    # =========================================================================
    # RESPONSE PATTERN FEATURES (always computed)
    # =========================================================================
    if resp_cols:
        scale_ranges = config["scale_ranges"]
        resp_scales = [c.replace("_response", "") for c in resp_cols]

        missing = [s for s in resp_scales if s not in scale_ranges]
        if missing:
            raise ValueError(f"Missing scale_ranges for: {missing}. Found: {list(scale_ranges.keys())}")

        # Mark illegal values as NaN
        for col in resp_cols:
            s = col.replace("_response", "")
            lo, hi = scale_ranges[s]
            bad = df[col].notna() & ((df[col] < lo) | (df[col] > hi))
            if bad.any():
                df.loc[bad, col] = np.nan

        # =====================================================================
        # Shannon Entropy over Rolling Window
        # =====================================================================
        # For each scale, compute Shannon entropy of response distribution
        # within a rolling window. Then average across scales.
        # Low entropy = responses concentrated (straightlining)
        # High entropy = responses spread uniformly (random responding)
        # A SHIFT in entropy (either direction) between blocks indicates
        # a change in response pattern - useful for detecting attention switches.
        # =====================================================================
        
        per_scale_entropy = []
        
        for col in resp_cols:
            scale_name = col.replace("_response", "")
            resp_series = df[col].values
            
            # Compute rolling Shannon entropy for this scale.
            # use pandas rolling so the entropy window matches the
            # RT/coherence rolling features (same window/center/min_periods
            # semantics), so entropy blocks and RT blocks align at boundaries.
            # Same NA rule as Adj RT Var (win): min_periods counts NON-missing
            # values, missing values inside the window are dropped, and windows
            # below min_periods (incl. the session edges) stay NaN -- not filled.
            _entropy_series = (
                pd.Series(resp_series)
                .rolling(window=window, center=center, min_periods=min_periods)
                .apply(shannon_entropy, raw=True)
            )
            entropy_vals = _entropy_series.to_numpy()
            
            per_scale_entropy.append(entropy_vals)
        
        # Average entropy across scales
        entropy_matrix = np.column_stack(per_scale_entropy)
        df["rating_entropy"] = np.nanmean(entropy_matrix, axis=1)
        
        # Also compute normalized entropy (0-1 scale based on max possible)
        # Max entropy for a scale with k possible values = log(k)
        max_entropies = []
        for col in resp_cols:
            s = col.replace("_response", "")
            lo, hi = scale_ranges[s]
            # validate scale range; otherwise log(k) for k<=0 silently
            # produces -inf/NaN and contaminates the normalized entropy column.
            if hi < lo:
                raise ValueError(
                    f"scale_ranges['{s}'] has hi ({hi}) < lo ({lo}); fix LVL_1_CONFIG['scale_ranges']"
                )
            k = max(1, hi - lo + 1)  # Number of possible values
            max_entropies.append(np.log(k))
        
        # Normalize each scale's entropy by its max, then average
        normalized_entropy = []
        for i, col in enumerate(resp_cols):
            normalized_entropy.append(per_scale_entropy[i] / max_entropies[i])
        
        norm_entropy_matrix = np.column_stack(normalized_entropy)
        df["rating_entropy_norm"] = np.nanmean(norm_entropy_matrix, axis=1)

        # Keep the PER-SCALE normalised entropy alongside the cross-scale average
        # (diagnostic columns; LVL_2 computes its own block-level entropy).
        for _i, _col in enumerate(resp_cols):
            df[f"rating_entropy_norm_{_col.replace('_response', '')}"] = normalized_entropy[_i]

    # === INDEX FEATURES ===
    df["trial_global"] = np.arange(n)
    df["trial_in_session"] = df.groupby("session").cumcount() if "session" in df.columns else np.arange(n)

    if "session" in df.columns:
        sessions = sorted(df["session"].dropna().unique())
        session_map = {s: i for i, s in enumerate(sessions)}
        df["session_indicator"] = df["session"].map(session_map).fillna(0)
    else:
        df["session_indicator"] = 0

    return df

