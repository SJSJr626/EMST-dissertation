def long_to_stim_level(df, config, participant_col='id', session_col='session', 
                        stim_col='stim_order', scale_col='scale'):
    """
    Convert long-format data to trial-level features.
    
    Parameters
    ----------
    df : pd.DataFrame
        Long-format data with one row per scale rating
    config : dict
        Configuration dictionary (required)
    
    Returns
    -------
    pd.DataFrame
        Trial-level data with one row per trial
        Preserves stim_label if present in input data.
    """
    # validate config['scale_ranges'] presence with a clear error.
    if "scale_ranges" not in config or not config["scale_ranges"]:
        raise ValueError(
            "long_to_stim_level: config['scale_ranges'] is required and must be non-empty"
        )
    scales = list(config["scale_ranges"].keys())

    # Resolve which RT representation feeds {scale}_rt / {scale}_residual*.
    # feature_rt_transform picks raw/log/boxcox; ses_wise_drift and
    # age_adjust_drift_residuals pick the base/age variant within it. LVL_0
    # computes all three representations (cell 7); this only selects which one
    # LVL_1 reads. use_residuals (read downstream by get_feature_column) then
    # picks the value vs. the residual WITHIN this same representation.
    _RT_VALUE_COL = {"raw": "rt_sec", "log": "log_rt", "boxcox": "bc_rt"}
    _RT_TAG = {"raw": "raw", "log": "log", "boxcox": "bc"}
    _transform = config["feature_rt_transform"]
    _rtval_col = _RT_VALUE_COL[_transform]
    _tag = _RT_TAG[_transform]
    _base = "per_ses" if config["ses_wise_drift"] else "overall"
    # Explicit flag, validated against what LVL_0 actually produced (also checked in
    # the LVL_1 run cell): a missing _age column must fail, not silently drop the pivot.
    _age_sfx = "_age" if config["age_adjust_drift_residuals"] else ""
    if _age_sfx and f"drift_residual_{_tag}_{_base}_age" not in df.columns:
        raise SystemExit(
            f"long_to_stim_level: age_adjust_drift_residuals=True but "
            f"drift_residual_{_tag}_{_base}_age is not in the LVL_0 handoff.")
    _pred_col = f"predicted_rt_{_tag}_{_base}"
    _resid_col = f"drift_residual_{_tag}_{_base}{_age_sfx}"

    df = df.copy()

    # Ensure numeric types
    df['rt_sec'] = pd.to_numeric(df['rt_sec'], errors='coerce')
    df['response'] = pd.to_numeric(df['response'], errors='coerce')
    if _rtval_col in df.columns:
        df[_rtval_col] = pd.to_numeric(df[_rtval_col], errors='coerce')
    if _pred_col in df.columns:
        df[_pred_col] = pd.to_numeric(df[_pred_col], errors='coerce')
    if _resid_col in df.columns:
        df[_resid_col] = pd.to_numeric(df[_resid_col], errors='coerce')
        df['_feature_residual_abs'] = df[_resid_col].abs()
    # rt_input: the single canonical RT metric resolved at cell 20. Pivoted to
    # {scale}_rt_input so LVL_2 can build all of its block features from ONE
    # column family instead of re-deriving the raw-vs-residual choice.
    if 'rt_input' in df.columns:
        df['rt_input'] = pd.to_numeric(df['rt_input'], errors='coerce')
    
    # Preserve stim_label: get unique stim_label per (participant, session, stim)
    # stim_label is the same for all scales within a stimulus
    stim_label_df = None
    if 'stim_label' in df.columns:
        # warn if any (pid, session, stim) cell has > 1 distinct stim_label;
        # .first() would silently swallow the inconsistency.
        _nunique_lab = (
            df.groupby([participant_col, session_col, stim_col])['stim_label']
              .nunique(dropna=True)
        )
        if (_nunique_lab > 1).any():
            import warnings as _w_ls4
            _w_ls4.warn(
                'long_to_stim_level: multiple stim_label values within the same '
                '(participant, session, stim_order); .first() used.',
                stacklevel=2,
            )
        stim_label_df = df.groupby([participant_col, session_col, stim_col])['stim_label'].first().reset_index()
    
    # Preserve condition: get unique condition per (participant, session, stim)
    # condition is the same for all rows of a participant (between-subjects)
    condition_df = None
    if 'condition' in df.columns:
        _nunique_cond = (
            df.groupby([participant_col, session_col, stim_col])['condition']
              .nunique(dropna=True)
        )
        if (_nunique_cond > 1).any():
            import warnings as _w_ls4b
            _w_ls4b.warn(
                'long_to_stim_level: multiple condition values within the same '
                '(participant, session, stim_order); .first() used.',
                stacklevel=2,
            )
        condition_df = df.groupby([participant_col, session_col, stim_col])['condition'].first().reset_index()
    
    # Pivot RT values (from whichever representation feature_rt_transform selects)
    rt_pivot = df.pivot_table(
        index=[participant_col, session_col, stim_col],
        columns=scale_col,
        values=_rtval_col,
        aggfunc='first'
    ).reset_index()
    rt_pivot.columns = [f"{c}_rt" if c in scales else c for c in rt_pivot.columns]
    
    # Pivot response values
    resp_pivot = df.pivot_table(
        index=[participant_col, session_col, stim_col],
        columns=scale_col,
        values='response',
        aggfunc='first'
    ).reset_index()
    resp_pivot.columns = [f"{c}_response" if c in scales else c for c in resp_pivot.columns]
    
    # Pivot predicted RT (same representation/base as the residual below)
    if _pred_col in df.columns:
        pred_pivot = df.pivot_table(
            index=[participant_col, session_col, stim_col],
            columns=scale_col,
            values=_pred_col,
            aggfunc='first'
        ).reset_index()
        pred_pivot.columns = [f"{c}_predicted" if c in scales else c for c in pred_pivot.columns]
    else:
        pred_pivot = None
    
    # Pivot drift residuals
    if _resid_col in df.columns:
        resid_pivot = df.pivot_table(
            index=[participant_col, session_col, stim_col],
            columns=scale_col,
            values=_resid_col,
            aggfunc='first'
        ).reset_index()
        resid_pivot.columns = [f"{c}_residual" if c in scales else c for c in resid_pivot.columns]
    else:
        resid_pivot = None
    
    # Pivot rt_input (canonical LVL_2 hand-off metric)
    if 'rt_input' in df.columns:
        rtin_pivot = df.pivot_table(
            index=[participant_col, session_col, stim_col],
            columns=scale_col,
            values='rt_input',
            aggfunc='first'
        ).reset_index()
        rtin_pivot.columns = [f"{c}_rt_input" if c in scales else c for c in rtin_pivot.columns]
    else:
        rtin_pivot = None

    # Pivot absolute residuals
    if '_feature_residual_abs' in df.columns:
        resid_abs_pivot = df.pivot_table(
            index=[participant_col, session_col, stim_col],
            columns=scale_col,
            values='_feature_residual_abs',
            aggfunc='first'
        ).reset_index()
        resid_abs_pivot.columns = [f"{c}_residual_abs" if c in scales else c for c in resid_abs_pivot.columns]
    else:
        resid_abs_pivot = None
    
    # Merge all pivots
    stim_lvl_df = rt_pivot.copy()
    
    for pivot_df in [resp_pivot, pred_pivot, resid_pivot, resid_abs_pivot, rtin_pivot]:
        if pivot_df is None:
            continue
        merge_cols = [c for c in pivot_df.columns if c not in [participant_col, session_col, stim_col]]
        stim_lvl_df = stim_lvl_df.merge(
            pivot_df[[participant_col, session_col, stim_col] + merge_cols],
            on=[participant_col, session_col, stim_col],
            how='left'
        )
    
    # Merge stim_label if it was present in input
    if stim_label_df is not None:
        stim_lvl_df = stim_lvl_df.merge(
            stim_label_df,
            on=[participant_col, session_col, stim_col],
            how='left'
        )
    
    # Merge condition if it was present in input
    if condition_df is not None:
        stim_lvl_df = stim_lvl_df.merge(
            condition_df,
            on=[participant_col, session_col, stim_col],
            how='left'
        )
    
    # Rename for consistency
    stim_lvl_df = stim_lvl_df.rename(columns={
        participant_col: 'id',
        session_col: 'session', 
        stim_col: 'stim_order'
    })
    
    return stim_lvl_df

