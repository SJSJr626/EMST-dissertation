# SHARED ROBUST SCALING (MAD) -- the single implementation used by every level
# =============================================================================
# Robust z = (x - median) / (MAD_TO_SD * MAD [+ eps]). Every MAD-based centring /
# scaling in LVL_1 and LVL_2 calls these functions. What a zero (or near-zero) MAD
# turns into differs by site; that choice is an explicit `zero_mad` argument at each
# call site rather than a hand-written variant. A zero MAD occurs in sessions whose
# Entropy (win) is 0 in most windows (long straight-lined stretches).

MAD_TO_SD = 1.4826   # 1.4826 x MAD estimates the SD of a normal distribution


def mad(x, axis=0, skipna=True):
    """Raw (unscaled) median absolute deviation about the median."""
    med_fn = np.nanmedian if skipna else np.median
    x = np.asarray(x, dtype=float)
    return med_fn(np.abs(x - np.nanmedian(x, axis=axis)), axis=axis)


def robust_z(x, center, raw_mad, eps=1e-8):
    """(x - center) / (MAD_TO_SD * raw_mad + eps) -- the one robust-z formula."""
    return (x - center) / (raw_mad * MAD_TO_SD + eps)


def robust_center_scale(x, zero_mad="floor", eps=1e-8, sd_below=1e-6, skipna_mad=True):
    """Median and robust scale of x (column-wise for a DataFrame / 2-D array).

    zero_mad -- how a (near-)zero MAD is handled:
      "floor": scale = MAD_TO_SD * MAD + eps   (MAD = 0 gives scale = eps)
      "sd":    a MAD <= sd_below is replaced by the SD (ddof=1) first, then as "floor"
      "zeros": scale = MAD_TO_SD * MAD + eps with eps normally 0; robust_scale returns
               0 where that scale is not > 0 (also when it is NaN)
    The center is the NaN-skipping median. skipna_mad=False takes the MAD with
    np.median, so any NaN in x makes it NaN.
    Returns (center, scale): floats for 1-D input, per-column Series for a DataFrame,
    per-column arrays for a 2-D array."""
    if zero_mad not in ("floor", "sd", "zeros"):
        raise ValueError(f"robust_center_scale: unknown zero_mad={zero_mad!r}")
    if isinstance(x, pd.DataFrame):
        pairs = [robust_center_scale(x[c], zero_mad, eps, sd_below, skipna_mad) for c in x.columns]
        return (pd.Series([p[0] for p in pairs], index=x.columns, dtype=float),
                pd.Series([p[1] for p in pairs], index=x.columns, dtype=float))
    arr = np.asarray(x, dtype=float)
    if arr.ndim == 2:
        pairs = [robust_center_scale(arr[:, j], zero_mad, eps, sd_below, skipna_mad) for j in range(arr.shape[1])]
        return np.array([p[0] for p in pairs]), np.array([p[1] for p in pairs])
    center = float(np.nanmedian(arr))
    raw = float((np.nanmedian if skipna_mad else np.median)(np.abs(arr - center)))
    if zero_mad == "sd" and not raw > sd_below:
        raw = float(pd.Series(arr).std())
    return center, raw * MAD_TO_SD + eps


def robust_scale(x, zero_mad="floor", eps=1e-8, sd_below=1e-6, skipna_mad=True):
    """Robust z of x (column-wise for a DataFrame / 2-D array); see robust_center_scale."""
    center, scale = robust_center_scale(x, zero_mad, eps, sd_below, skipna_mad)
    if zero_mad != "zeros":
        return (x - center) / scale
    if isinstance(x, pd.DataFrame):
        ok = scale > 0
        return pd.DataFrame({c: ((x[c] - center[c]) / scale[c]) if ok[c] else 0.0 for c in x.columns},
                            index=x.index)
    if isinstance(x, pd.Series):
        return (x - center) / scale if scale > 0 else pd.Series(0.0, index=x.index)
    arr = np.asarray(x, dtype=float)
    return (arr - center) / scale if scale > 0 else np.zeros_like(arr)


