def merge_block_labels_to_long(long_df, features_df, block_cols=None):
    """
    Merge block labels from features_df (wide) back to long_df.
    
    This is more efficient than melting features_df back to long format
    because we only transfer the block assignment columns.
    
    Parameters
    ----------
    long_df : pd.DataFrame
        Original long-format data with id, session, stim_order, scale columns
    features_df : pd.DataFrame
        Wide-format features with block_{method} columns
    block_cols : list, optional
        Specific block columns to merge. If None, merges all block_* columns.
    
    Returns
    -------
    pd.DataFrame
        long_df with block labels added
    """
    if features_df is None or len(features_df) == 0:
        return long_df
    
    long_df = long_df.copy()
    
    # Identify block columns
    if block_cols is None:
        block_cols = [c for c in features_df.columns if c.startswith('block_')]
    
    if not block_cols:
        print("  No block columns found in features_df")
        return long_df
    
    # Select merge keys and block columns from features_df
    merge_keys = ['id', 'session', 'stim_order']
    cols_to_merge = merge_keys + block_cols
    cols_to_merge = [c for c in cols_to_merge if c in features_df.columns]
    
    block_lookup = features_df[cols_to_merge].copy()
    
    # Ensure consistent dtypes for merge
    for key in merge_keys:
        if key in long_df.columns and key in block_lookup.columns:
            long_df[key] = long_df[key].astype(str)
            block_lookup[key] = block_lookup[key].astype(str)
    
    # Drop existing block columns to avoid duplicates
    existing_block_cols = [c for c in block_cols if c in long_df.columns]
    if existing_block_cols:
        long_df = long_df.drop(columns=existing_block_cols)
    
    # Merge block labels to long format
    long_with_blocks = long_df.merge(
        block_lookup,
        on=merge_keys,
        how='left'
    )
    
    n_matched = long_with_blocks[block_cols[0]].notna().sum() if block_cols else 0
    print(f"  Merged {len(block_cols)} block columns to long_df ({n_matched}/{len(long_with_blocks)} rows matched)")
    
    return long_with_blocks


