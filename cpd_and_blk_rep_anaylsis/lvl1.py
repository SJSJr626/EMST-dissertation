def _jsonable(obj):
    if isinstance(obj, pd.DataFrame):
        return obj.astype(object).where(pd.notna(obj), None).to_dict(orient="records")
    if isinstance(obj, pd.Series):
        return obj.astype(object).where(pd.notna(obj), None).to_dict()
    if isinstance(obj, dict):
        return {str(k): _jsonable(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple, set)):
        return [_jsonable(v) for v in obj]
    if isinstance(obj, np.integer):
        return int(obj)
    if isinstance(obj, np.floating):
        return None if np.isnan(obj) else float(obj)
    if isinstance(obj, np.bool_):
        return bool(obj)
    return obj


def file_sha256(path, chunk=1 << 20):
    """SHA-256 of a file's bytes: the content identity of the raw input, recorded by LVL_0 and checked downstream."""
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for b in iter(lambda: f.read(chunk), b""):
            h.update(b)
    return h.hexdigest()


def dump_level_json(level, config, results=None, extra=None, name=None):
    """Write the level's run log: <name>_parameters.json, where name is the stem of the
    output it describes (e.g. lv0_out_<ts>), or <level>_parameters_<ts>.json without one."""
    ts = datetime.now().strftime("%Y%m%d_%H%M%S")
    path = RUN_LOG_DIR / (f"{name}_parameters.json" if name else f"{level}_parameters_{ts}.json")
    payload = {
        "level": level,
        "pipeline_version": PIPELINE_VERSION,
        "software": software_versions(),
        "timestamp": ts,
        "input_long_path": str(INPUT_LONG_PATH),
        "figures_dir": str(FIG_DIR),
        "figures_saved": int(_FIG_SAVE_STATE["n"]),
        "parameters": _jsonable(config),
        "statistical_results": _jsonable(results or {}),
        "outputs": _jsonable(extra or {}),
    }
    with open(path, "w") as f:
        json.dump(payload, f, indent=2, default=str)
    print(f"  {level} parameter/results JSON -> {path}")
    return path

