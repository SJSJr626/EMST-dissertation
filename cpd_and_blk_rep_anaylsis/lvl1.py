def _labels_to_all_rows(labels_obs, observed):
    """Map labels fitted on the observed rows back onto every row.

    An unobserved row (rolling-window edge, or a stimulus dropped by an RT threshold
    under rt_threshold_na_handling="drop_stimulus") takes the
    label of the nearest PRECEDING observed row; rows before the first observed row
    take the first observed label. So an unobserved run inside a block stays in that
    block, a run sitting exactly at a boundary joins the block before it, leading /
    trailing runs join the first / last block, and an unobserved row can never start
    a block of its own -- missing values neither create nor move a changepoint."""
    observed = np.asarray(observed, dtype=bool)
    labels_obs = np.asarray(labels_obs)
    idx = np.flatnonzero(observed)
    prev = np.searchsorted(idx, np.arange(len(observed)), side="right") - 1
    return labels_obs[np.clip(prev, 0, len(idx) - 1)]


def _on_observed_rows(detect, feature_names, config):
    """Run `detect` only on stimuli where every feature it segments on is observed.

    Nothing is imputed: NaN rows are removed before detection and get their block from
    _labels_to_all_rows afterwards. Methods with no features (Fixed_*) are unchanged."""
    def run(f, pid=None, sid=None):
        cols = [c for c in (get_feature_column(nm, f, config) for nm in feature_names) if c]
        if not cols:
            return detect(f, pid=pid, sid=sid)
        observed = f[cols].notna().all(axis=1).to_numpy()
        if observed.all():
            return detect(f, pid=pid, sid=sid)
        if not observed.any():
            return np.zeros(len(f), dtype=int)
        labels = detect(f.loc[observed].reset_index(drop=True), pid=pid, sid=sid)
        return _labels_to_all_rows(labels, observed)
    return run


def create_block_methods(config):
    """
    Create block detection method registry from config.
    
    Creates individual methods for EACH feature in the feature lists,
    plus composite methods that combine all features.
    
    Method Naming Convention
    ------------------------
    Individual feature methods:
    - HMM_[N]_[Feature]: HMM on single feature (N states)
    - CPD_[Feature]: MAD changepoint on single feature
    - PELT_[Feature]: PELT on single feature

    Composite methods:
    - HMM_Attention_comp_[N]: HMM on all hmm_composite features
    - CPD_Attention_comp: CPD on all cp_composite features
    - PELT_Attention_comp: PELT on all pelt_composite features

    Fixed_[N] (fixed_block_sizes) are registered here; the matched controls
    Fixed_[Method]_based are built after detection (control_block_count).
    """
    methods = {}
    # use_residuals isn't read in this function; downstream detection
    # functions resolve column choice themselves via get_feature_column.
    cp_comp_method = config["cp_comp_method"]
    
    # Get feature lists from config
    hmm_features = config["hmm_features"]
    hmm_composite = config["hmm_composite"]
    cp_features = config["cp_features"]
    cp_composite = config["cp_composite"]
    
    # Helper to create clean method name from feature display name
    def feature_to_name(feature):
        """Convert display name to method-safe name."""
        return feature.replace(" ", "_").replace("(", "").replace(")", "")
    
    # Helper to determine defined_on. Single source of truth: cell 15's
    # FEATURE_REGISTRY[feature]["defined_on"]. Unknown features fall through
    # to "mixed" so a misnamed composite still registers without crashing.
    def get_defined_on_single(feature):
        return FEATURE_REGISTRY.get(feature, {}).get("defined_on", "mixed")
    
    # Fixed blocks (skip if None)
    if config["fixed_block_sizes"] is not None:
        for size in config["fixed_block_sizes"]:
            methods[f"Fixed_{size}"] = {
                "func": lambda f, pid=None, sid=None, s=size: detect_blocks_fixed(len(f), s),
                "defined_on": "time",
                "features": [],
                "description": f"Fixed {size}-trial blocks",
            }
    
    # Method-family filter: only register families listed in cpd_method_types
    method_types = config["cpd_method_types"]
    method_types_set = {t.upper() for t in method_types}

    # ==========================================================================
    # HMM METHODS - One per feature in hmm_features
    # ==========================================================================
    if "HMM" in method_types_set and config["hmm_n_states"] is not None:
        for feature in hmm_features:
            feat_name = feature_to_name(feature)
            defined_on = get_defined_on_single(feature)
            
            for n in config["hmm_n_states"]:
                method_name = f"HMM_{n}_{feat_name}"
                methods[method_name] = {
                    "func": _on_observed_rows(
                        lambda f, pid=None, sid=None, n=n, fl=[feature], c=config:
                            detect_blocks_hmm(f, n, fl, c, participant_id=pid, session_id=sid),
                        [feature], config),
                    "defined_on": defined_on,
                    "features": [feature],
                    "description": f"HMM on {feature} ({n} states)",
                }
        
        # HMM Composite method (all hmm_composite features combined)
        if hmm_composite:
            for n in config["hmm_n_states"]:
                methods[f"HMM_Attention_comp_{n}"] = {
                    "func": _on_observed_rows(
                        lambda f, pid=None, sid=None, n=n, fl=hmm_composite, c=config:
                            detect_blocks_hmm(f, n, fl, c, participant_id=pid, session_id=sid),
                        hmm_composite, config),
                    "defined_on": "attention_composite",
                    "features": list(hmm_composite),
                    "description": f"HMM composite ({n} states)",
                }
    
    # ==========================================================================
    # MAD-CPD METHODS - One per feature in cp_features
    # ==========================================================================
    if "MAD" in method_types_set and config["cp_k"] is not None:
        for feature in cp_features:
            feat_name = feature_to_name(feature)
            defined_on = get_defined_on_single(feature)
            
            method_name = f"CPD_{feat_name}"
            methods[method_name] = {
                "func": _on_observed_rows(
                    lambda f, pid=None, sid=None, fl=[feature], c=config:
                        detect_blocks_cpd(f, fl, c, composite_method="average",
                                           participant_id=pid, session_id=sid),
                    [feature], config),
                "defined_on": defined_on,
                "features": [feature],
                "description": f"CPD on {feature}",
            }
        
        # CPD Composite method (all cp_composite features combined)
        if cp_composite:
            methods["CPD_Attention_comp"] = {
                "func": _on_observed_rows(
                    lambda f, pid=None, sid=None, fl=cp_composite, c=config:
                        detect_blocks_cpd(f, fl, c, composite_method=cp_comp_method,
                                           participant_id=pid, session_id=sid),
                    cp_composite, config),
                "defined_on": "attention_composite",
                "features": list(cp_composite),
                "description": f"CPD composite via {cp_comp_method}",
            }
    
    # ==========================================================================
    # PELT METHODS - One per feature in pelt_features
    # ==========================================================================
    if "PELT" in method_types_set:
        pelt_features = config["pelt_features"]
        pelt_composite = config["pelt_composite"]
        _pen_uni_str = config["pelt_pen_uni"]
        _pen_multi_str = config["pelt_pen_multi"]
        pelt_cost_str = config["pelt_model"]

        for feature in pelt_features:
            feat_name = feature_to_name(feature)
            defined_on = get_defined_on_single(feature)
            method_name = f"PELT_{feat_name}"
            methods[method_name] = {
                "func": _on_observed_rows(
                    lambda f, pid=None, sid=None, fl=[feature], c=config:
                        detect_blocks_pelt(f, fl, c, composite_method="average",
                                            participant_id=pid, session_id=sid),
                    [feature], config),
                "defined_on": defined_on,
                "features": [feature],
                "description": f"PELT ({pelt_cost_str}, pen={_pen_uni_str}) on {feature}",
            }

        if pelt_composite:
            methods["PELT_Attention_comp"] = {
                "func": _on_observed_rows(
                    lambda f, pid=None, sid=None, fl=pelt_composite, c=config:
                        detect_blocks_pelt(f, fl, c, composite_method=cp_comp_method,
                                            participant_id=pid, session_id=sid),
                    pelt_composite, config),
                "defined_on": "attention_composite",
                "features": list(pelt_composite),
                "description": f"PELT ({pelt_cost_str}, pen={_pen_multi_str}) composite via {cp_comp_method}",
            }

    return methods

